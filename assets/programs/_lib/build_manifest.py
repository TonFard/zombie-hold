"""Build the runtime manifest from the exported atoms.

    conda run -n sand3d python assets/programs/_lib/build_manifest.py

Every atom writes a ``<id>.json`` next to its ``<id>.glb``. This script walks
``assets/models`` and collects those into one manifest per region, plus a
TypeScript type file the game imports. The manifest is what the runtime loader
reads: it is the tree, made flat for streaming.
"""
from __future__ import annotations

import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
MODEL_DIR = os.path.join(ROOT, "assets", "models")
OUT_DIR = os.path.join(ROOT, "src", "game", "world")
TS_OUT = os.path.join(OUT_DIR, "assets-manifest.ts")


def collect():
    atoms = []
    if not os.path.isdir(MODEL_DIR):
        return atoms
    for dirpath, _dirnames, filenames in os.walk(MODEL_DIR):
        for name in sorted(filenames):
            if not name.endswith(".json"):
                continue
            if name.startswith("manifest-"):
                continue  # 这些是聚合清单，不是原子描述
            path = os.path.join(dirpath, name)
            with open(path, "r", encoding="utf-8") as fh:
                info = json.load(fh)
            if "id" not in info:
                continue
            glb = os.path.join(dirpath, name[:-5] + ".glb")
            info["file"] = os.path.relpath(glb, ROOT).replace("\\", "/")
            info["exists"] = os.path.exists(glb)
            atoms.append(info)
    return sorted(atoms, key=lambda a: a["id"])


def write_ts(atoms):
    lines = [
        "// Generated by assets/programs/_lib/build_manifest.py — do not edit by hand.",
        "",
        "export interface AtomDescriptor {",
        "  id: string;",
        "  region: string;",
        "  site: string;",
        "  room: string;",
        "  object: string;",
        "  part: string | null;",
        "  style: string;",
        "  size_m: [number, number, number];",
        "  /** sand3d 原始轴序：X 宽、Y 深、Z 高 */",
        "  size_m_s3d: [number, number, number];",
        "  tri: number;",
        "  origin: string;",
        "  materials: string[];",
        "  collider: string;",
        "  instanced: boolean;",
        "  tags: string[];",
        "  states: string[];",
        "  file: string;",
        "  exists: boolean;",
        "}",
        "",
        "export const ATOM_MANIFEST: AtomDescriptor[] = " + json.dumps(atoms, indent=2, ensure_ascii=False) + ";",
        "",
    ]
    with open(TS_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main():
    atoms = collect()
    os.makedirs(OUT_DIR, exist_ok=True)
    write_ts(atoms)

    by_region: dict = {}
    for a in atoms:
        by_region.setdefault(a["region"], []).append(a)
    for region, items in sorted(by_region.items()):
        out = os.path.join(MODEL_DIR, f"manifest-{region}.json")
        with open(out, "w", encoding="utf-8") as fh:
            json.dump({"region": region, "atoms": items}, fh, ensure_ascii=False, indent=2)

    missing = [a["id"] for a in atoms if not a["exists"]]
    print(f"{len(atoms)} atoms in {len(by_region)} regions -> {TS_OUT}")
    for region, items in sorted(by_region.items()):
        print(f"  {region}: {len(items)}")
    if missing:
        print(f"MISSING GLB for {len(missing)}: {missing[:8]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
