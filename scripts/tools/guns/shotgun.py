"""铁砧霰弹枪（全自动，弹匣供弹）。坐标系见 kit.py。

各级外观：0 短弹匣   1 加长弹匣、加粗扼流   2 加长管状弹仓 + 观察窗   3 枪管散热罩   4 侧挂弹袋
          5 龙息弹枪口（发光）   6 大弹鼓、氚光准星、收束扼流   7 导轨 + 鬼环照门
"""
import math

from kit import Gun, M

SIGHT = 0.068    # 瞄准线：准星珠中心
RIB = 0.058      # 通风肋顶面
BORE = 0.034


def build(g: Gun) -> None:
    # ---------------- 枪托（木，握把一体） ----------------
    g.prof([(-0.03, 0.03), (-0.03, -0.01), (-0.012, -0.03), (-0.03, -0.1), (-0.06, -0.1), (-0.07, -0.05), (-0.36, -0.1), (-0.37, -0.1),
            (-0.37, 0.02), (-0.2, 0.028, -0.07, 0.03)], 0.04, M.wood(), bevel=0.008, seg=3)
    g.box((0.044, 0.125, 0.016), (0, -0.04, -0.377), M.rubber(), bevel=0.004)                # 托底板
    for i in range(5):
        g.box((0.045, 0.003, 0.0165), (0, -0.085 + i * 0.022, -0.3775), M.polymer(), bevel=0.0008)
    g.torus(0.008, 0.002, (0.0, -0.085, -0.3), M.steel(), seg=16, rseg=6, axis="x")          # 背带环
    # 握把方格纹
    for i in range(5):
        for j in range(3):
            for x in (0.0202, -0.0202):
                g.box((0.0012, 0.0046, 0.0046), (x, -0.038 - i * 0.011, -0.03 - j * 0.009 - i * 0.002), M.polymer(), bevel=0.0004, rot=(0.6, 0, 0))

    # ---------------- 机匣 ----------------
    rc = g.prof([(-0.03, -0.012), (0.2, -0.012), (0.2, 0.05), (-0.02, 0.05), (-0.03, 0.04)], 0.046, M.gunmetal(), bevel=0.004, seg=3)
    g.box((0.012, 0.024, 0.07), (-0.023, 0.024, 0.1), cut=rc, bevel=0)                       # 抛壳口
    g.cyl(0.0095, 0.045, (-0.012, 0.026, 0.078), M.red(), seg=16)                            # 膛里的一发霰弹
    g.cyl(0.0098, 0.009, (-0.012, 0.026, 0.07), M.brass(), seg=16)
    g.box((0.004, 0.006, 0.014), (-0.0245, 0.03, 0.15), M.steel(), bevel=0.001)              # 拉机柄
    # 扳机护圈 + 扳机 + 保险 + 销子
    # 后端一直接到握把前缘，不悬空
    g.prof([(0.078, -0.012), (0.078, -0.04, 0.062, -0.04), (0.03, -0.04), (-0.014, -0.032), (-0.012, -0.0285), (0.031, -0.0365), (0.06, -0.0365),
            (0.0745, -0.0365, 0.0745, -0.012)], 0.012, M.gunmetal(), bevel=0.0008)
    g.prof([(0.046, -0.012), (0.051, -0.012), (0.049, -0.026, 0.043, -0.032), (0.04, -0.03), (0.045, -0.02)], 0.006, M.steel(), bevel=0.0008)
    g.box((0.008, 0.004, 0.018), (0, 0.052, -0.006), M.steel(), bevel=0.001)
    g.pin(0.004, 0.03, 0.003, 0.0232)
    g.pin(0.004, 0.16, 0.003, 0.0232)
    g.box((0.034, 0.01, 0.072), (0, -0.016, 0.132), M.blued(), bevel=0.002)                  # 弹匣井

    # ---------------- 弹匣（可动）：0 短、1–5 长、6 起弹鼓 ----------------
    with g.part("mag"):
        for lo, hi, h in ((0, 0, 0.1), (1, 5, 0.12)):
            with g.tier(lo, hi):
                m = g.box((0.03, h, 0.066), (0, -0.02 - h / 2, 0.132 + h * 0.06), M.polymer(), bevel=0.005, seg=3, rot=(-0.12, 0, 0))
                # 侧面观察窗：三枚红色弹壳
                for i in range(3):
                    g.box((0.04, 0.012, 0.03), (0, -0.045 - i * 0.022, 0.136 + i * 0.003), cut=m, bevel=0)
                    # 弹壳顺着枪管方向躺在弹匣里，从侧窗看到的是一段红色弹身
                    g.cyl(0.009, 0.052, (0, -0.045 - i * 0.022, 0.11 + i * 0.003), M.red(), seg=14)
                g.box((0.033, 0.012, 0.07), (0, -0.024 - h, 0.132 + h * 0.12), M.rubber(), bevel=0.003, rot=(-0.12, 0, 0))
        with g.tier(6):
            g.box((0.03, 0.034, 0.06), (0, -0.034, 0.132), M.polymer(), bevel=0.003)
            g.cyl(0.056, 0.05, (-0.025, -0.078, 0.132), M.polymer(), axis="x", seg=36, bevel=0.004)
            g.cyl(0.02, 0.005, (0.025, -0.078, 0.132), M.gunmetal(), axis="x", seg=20)
            for i in range(8):
                a = math.tau * i / 8
                g.box((0.002, 0.004, 0.026), (0.0252, -0.078 + math.sin(a) * 0.038, 0.132 + math.cos(a) * 0.038), M.rubber(), bevel=0.0006, rot=(-a, 0, 0))

    # ---------------- 枪管 + 通风肋 + 准星 ----------------
    g.tube(0.0145, 0.0098, 0.555, (0, BORE, 0.2), M.blued(), seg=24)
    g.box((0.01, 0.005, 0.54), (0, RIB - 0.0025, 0.47), M.gunmetal(), bevel=0.001)
    for i in range(18):
        g.box((0.005, 0.006, 0.006), (0, 0.0525, 0.215 + i * 0.03), M.blued(), bevel=0.0008)  # 肋的支柱
    g.sphere(0.003, (0, RIB + 0.002, 0.46), M.glow(0xf2f2e6, 1.0), seg=12)                    # 中珠
    g.box((0.006, SIGHT - RIB + 0.002, 0.012), (0, (SIGHT + RIB) / 2 - 0.002, 0.743), M.blued(), bevel=0.001)
    with g.tier(0, 5):
        g.sphere(0.0048, (0, SIGHT, 0.745), M.glow(0xff8a2a, 2.6), seg=14)
    with g.tier(6):
        g.sphere(0.0048, (0, SIGHT, 0.745), M.glow(0x9dffa8, 3.2), seg=14)
    # 扼流管：0 细、1–5 加粗、6 起收束
    for lo, hi, r in ((0, 0, 0.0158), (1, 5, 0.0178), (6, 8, 0.017)):
        with g.tier(lo, hi):
            g.tube(r, 0.0102, 0.032, (0, BORE, 0.75), M.blued(), seg=24)
    # 5 级：龙息弹枪口装置 + 发光条
    with g.tier(5):
        g.lathe([(0.0105, 0), (0.019, 0), (0.024, 0.02), (0.02, 0.04), (0.0125, 0.04)], (0, BORE, 0.772), M.blued(), seg=24, closed=True)
        g.cyl(0.0122, 0.001, (0, BORE, 0.8105), M.glow(0xff5a1a, 2.6), seg=20, bevel=0)
        for x in (0.0146, -0.0146):
            g.box((0.002, 0.003, 0.36), (x, BORE + 0.002, 0.4), M.glow(0xff7a2a, 2.0), bevel=0)

    # ---------------- 管状弹仓（2 级加长，带观察窗） ----------------
    for lo, hi, tube in ((0, 1, 0.42), (2, 8, 0.52)):
        with g.tier(lo, hi):
            tb = g.cyl(0.0125, tube, (0, -0.006, 0.2), M.gunmetal(), seg=22)
            g.cyl(0.0146, 0.02, (0, -0.006, 0.2 + tube), M.steel(), seg=22)
            g.box((0.012, 0.034, 0.012), (0, 0.012, 0.2 + tube - 0.02), M.steel(), bevel=0.002)   # 枪管箍
            if lo >= 2:
                for i in range(5):
                    g.box((0.01, 0.008, 0.016), (0.0115, -0.006, 0.24 + i * 0.022), cut=tb, bevel=0)
                    g.box((0.004, 0.0075, 0.0155), (0.0085, -0.006, 0.24 + i * 0.022), M.red(), bevel=0)

    # ---------------- 护木（可动，全自动枪不拉，但换弹时左手扶着） ----------------
    with g.part("pump"):
        g.box((0.042, 0.042, 0.17), (0, -0.005, 0.37), M.wood(), bevel=0.014, seg=3)
        # 防滑纹：一圈圈比护木略粗的环（截面和护木同样的圆角）
        for i in range(9):
            g.box((0.0434, 0.0434, 0.004), (0, -0.005, 0.302 + i * 0.017), M.polymer(), bevel=0.0145, seg=3)
        # 连杆：贴着弹仓管两侧的深色钢条
        for x in (0.0135, -0.0135):
            g.box((0.004, 0.007, 0.12), (x, -0.006, 0.27), M.blued(), bevel=0.001)

    # 3 级：枪管散热罩
    with g.tier(3):
        hs = g.box((0.036, 0.022, 0.32), (0, BORE + 0.012, 0.4), M.gunmetal(), bevel=0.008, seg=3)
        g.box((0.031, 0.03, 0.34), (0, BORE + 0.003, 0.4), cut=hs, bevel=0)
        for i in range(8):
            g.box((0.05, 0.01, 0.022), (0, BORE + 0.015, 0.26 + i * 0.038), cut=hs, bevel=0)
    # 4 级：侧挂弹袋（4 发）
    with g.tier(4):
        g.box((0.006, 0.04, 0.11), (0.027, 0.02, 0.09), M.polymer(), bevel=0.002)
        for i in range(4):
            g.cyl(0.0095, 0.036, (0.036, 0.004, 0.05 + i * 0.026), M.red(), axis="y", seg=16)
            g.cyl(0.0098, 0.009, (0.036, 0.0, 0.05 + i * 0.026), M.brass(), axis="y", seg=16)
    # 7 级：顶部导轨 + 鬼环照门（环心和准星珠同高）
    with g.tier(7):
        g.rail(0.0, 0.16, RIB)
        g.box((0.014, 0.005, 0.01), (0, RIB + 0.0025, 0.03), M.blued(), bevel=0.001)
        g.torus(0.0085, 0.0018, (0, SIGHT, 0.03), M.blued(), seg=28, rseg=8)
        for x in (0.0125, -0.0125):
            g.box((0.003, 0.018, 0.008), (x, RIB + 0.012, 0.03), M.blued(), bevel=0.001)


def info(t: int) -> dict:
    return {
        "gripR": (0, -0.07, -0.03),
        "gripL": (0, -0.03, 0.37),
        "muzzle": (0, BORE, 0.812 if t >= 5 else 0.782),
        "eject": (-0.024, 0.024, 0.1),
        "sight": (0, SIGHT, 0.03),
        "eyeRelief": 0.2,
        "slideTravel": 0.08,
        "action": "auto",
    }
