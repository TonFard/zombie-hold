"""铁幕轻机枪。坐标系见 kit.py。

各级外观：0 基础   2 两脚架脚垫、氚光瞄具   4 枪管散热片   5 压制射击发光条   6 弹药箱黄色标签
          7 穿甲弹链（黑色弹头）   8 反射式瞄具
"""
from kit import Gun, M

BORE = 0.038
SL = 0.118       # 机瞄瞄准线
RY = 0.13        # 反射式瞄具红点
BZ = 0.26        # 枪管起点
MZ = BZ + 0.42   # 消焰器起点
BOX_Z = 0.165    # 弹药箱中心（在扳机护圈前面）


def build(g: Gun) -> None:
    # ---------------- 机匣 + 供弹盖 ----------------
    rc = g.prof([(-0.05, -0.02), (0.26, -0.02), (0.26, 0.07), (0.24, 0.08), (-0.04, 0.08), (-0.05, 0.07)], 0.062, M.gunmetal(), bevel=0.005, seg=3)
    g.box((0.008, 0.008, 0.14), (-0.031, 0.046, 0.15), cut=rc, bevel=0)                       # 拉机柄槽
    g.box((0.066, 0.016, 0.16), (0, 0.086, 0.08), M.gunmetal(), bevel=0.004, seg=3)
    g.cyl(0.005, 0.07, (-0.035, 0.094, -0.004), M.steel(), axis="x", seg=12)                  # 铰链
    g.box((0.01, 0.008, 0.02), (0.034, 0.084, 0.15), M.steel(), bevel=0.0015)                 # 盖锁
    g.rail(0.0, 0.14, 0.104, w=0.024)
    g.pin(0.03, 0.0, 0.004, 0.031)
    g.pin(0.03, 0.24, 0.004, 0.031)
    for x in (0.0312, -0.0312):
        g.box((0.0012, 0.004, 0.2), (x, 0.004, 0.1), M.gunmetal(), bevel=0.0005)
    with g.part("bolt"):
        g.box((0.02, 0.012, 0.012), (-0.04, 0.046, 0.18), M.steel(), bevel=0.002)
        g.cyl(0.008, 0.014, (-0.064, 0.046, 0.18), M.polymer(), axis="x", seg=14)

    # ---------------- 握把 + 扳机护圈 ----------------
    g.prof([(-0.03, -0.018), (0.1, -0.018), (0.1, -0.03), (0.02, -0.034), (-0.002, -0.15), (-0.044, -0.146), (-0.03, -0.04)], 0.036, M.polymer(), bevel=0.005, seg=3)
    g.prof([(0.096, -0.03), (0.096, -0.064, 0.078, -0.064), (0.034, -0.064), (0.014, -0.046), (0.019, -0.044), (0.036, -0.0605), (0.076, -0.0605),
            (0.0925, -0.0605, 0.0925, -0.03)], 0.012, M.polymer(), bevel=0.0008)
    g.prof([(0.054, -0.032), (0.059, -0.032), (0.056, -0.05, 0.05, -0.056), (0.047, -0.053), (0.052, -0.044)], 0.006, M.steel(), bevel=0.0008)
    for i in range(7):
        for x in (0.0182, -0.0182):
            g.box((0.0012, 0.0042, 0.028), (x, -0.062 - i * 0.012, -0.012 - i * 0.0024), M.rubber(), bevel=0.0005, rot=(0.19, 0, 0))

    # ---------------- 枪管：重枪管 + 带孔隔热罩 + 提把 + 消焰器 ----------------
    g.tube(0.014, 0.0062, 0.42, (0, BORE, BZ), M.blued(), seg=24)
    sh = g.tube(0.024, 0.021, 0.26, (0, BORE, BZ), M.gunmetal(), seg=28)
    for i in range(7):
        z = BZ + 0.024 + i * 0.034
        g.cyl(0.0048, 0.07, (-0.035, BORE + 0.01, z), cut=sh, axis="x", seg=12, bevel=0)
        g.cyl(0.0048, 0.04, (0, BORE, z + 0.017), cut=sh, axis="y", seg=12, bevel=0)
    for z in (BZ, BZ + 0.254):
        g.cyl(0.0248, 0.006, (0, BORE, z), M.blued(), seg=28)
    g.box((0.012, 0.012, 0.012), (0, 0.066, BZ + 0.04), M.blued(), bevel=0.002)
    g.rod((0.0, 0.09, BZ), (0.0, 0.09, BZ + 0.12), 0.007, M.polymer())                        # 提把
    g.rod((0.0, 0.062, BZ + 0.02), (0.0, 0.09, BZ), 0.005, M.blued())
    g.rod((0.0, 0.062, BZ + 0.1), (0.0, 0.09, BZ + 0.12), 0.005, M.blued())
    fh = g.lathe([(0.0066, 0), (0.014, 0.004), (0.018, 0.01), (0.018, 0.054), (0.0155, 0.06), (0.0066, 0.06)], (0, BORE, MZ), M.blued(), seg=24, closed=True)
    g.box((0.05, 0.005, 0.034), (0, BORE, MZ + 0.032), cut=fh, bevel=0)
    g.box((0.005, 0.05, 0.034), (0, BORE, MZ + 0.032), cut=fh, bevel=0)
    with g.tier(4):
        for i in range(5):
            g.tube(0.028, 0.0135, 0.003, (0, BORE, BZ + 0.275 + i * 0.02), M.steel(), seg=24, bevel=0.0004)
    with g.tier(5):
        for x in (0.0255, -0.0255):
            g.box((0.002, 0.003, 0.22), (x, BORE, BZ + 0.13), M.glow(0x6ad0ff, 2.0), bevel=0)

    # ---------------- 机瞄 ----------------
    dark = M.blued()
    g.box((0.032, 0.01, 0.012), (0, 0.106, 0.0), M.anodized(), bevel=0.002)
    with g.tier(0, 7):
        for x in (0.0065, -0.0065):
            g.box((0.006, 0.018, 0.008), (x, 0.119, 0.0), dark, bevel=0.0008)
        for lo, hi, m in ((0, 1, M.glow(0xf2f2e6, 1.1)), (2, 7, M.glow(0x7dff8a, 2.4))):
            with g.tier(lo, hi):
                for x in (0.0065, -0.0065):
                    g.box((0.0022, 0.0022, 0.001), (x, SL, -0.0045), m, bevel=0)
    with g.tier(8):
        g.box((0.026, 0.004, 0.018), (0, 0.11, -0.004), dark, bevel=0.001)                    # 折倒的照门
    fz = MZ - 0.03
    g.box((0.031, 0.05, 0.016), (0, 0.07, fz), M.gunmetal(), bevel=0.003)                     # 准星箍（咬住枪管）
    for x in (0.014, -0.014):
        g.box((0.003, 0.04, 0.012), (x, 0.114, fz), dark, bevel=0.001)                        # 护翼
    g.box((0.006, SL + 0.004 - 0.094, 0.006), (0, (SL + 0.004 + 0.094) / 2, fz), dark, bevel=0.0008)
    with g.tier(0, 1):
        g.box((0.0076, 0.0076, 0.001), (0, SL, fz - 0.0045), M.glow(0xff8a2a, 2.6), bevel=0)
    with g.tier(2):
        g.box((0.0076, 0.0076, 0.001), (0, SL, fz - 0.0045), M.glow(0x9dffa8, 3.2), bevel=0)
    # 8 级：反射式瞄具（开放式镜框）
    with g.tier(8):
        g.box((0.036, 0.01, 0.05), (0, 0.109, 0.065), M.anodized(), bevel=0.003)
        for x in (0.016, -0.016):
            g.box((0.004, 0.046, 0.03), (x, 0.137, 0.07), M.anodized(), bevel=0.0012)
        g.box((0.036, 0.004, 0.03), (0, 0.158, 0.07), M.anodized(), bevel=0.0012)
        g.box((0.006, 0.006, 0.012), (0.021, 0.14, 0.068), M.rubber(), bevel=0.001)
        g.box((0.0024, 0.0024, 0.001), (0, RY, 0.085), M.glow(0xff3020, 3.5), bevel=0)

    # ---------------- 两脚架（折叠在枪管下） ----------------
    g.box((0.026, 0.012, 0.02), (0, 0.014, BZ + 0.28), M.blued(), bevel=0.002)
    for x in (0.012, -0.012):
        g.rod((x, 0.01, BZ + 0.28), (x * 1.3, 0.004, BZ + 0.1), 0.004, M.steel())
        with g.tier(2):
            g.sphere(0.0055, (x * 1.3, 0.004, BZ + 0.098), M.rubber(), seg=12)

    # ---------------- 弹药箱（可动）+ 弹链（可动：随射击被拽进机匣） ----------------
    with g.part("mag", (0, -0.04, BOX_Z)):
        g.box((0.07, 0.11, 0.1), (0.012, -0.095, BOX_Z), M.olive(), bevel=0.006, seg=3)
        g.box((0.074, 0.012, 0.104), (0.012, -0.039, BOX_Z), M.olive(), bevel=0.003)
        for z in (BOX_Z - 0.03, BOX_Z + 0.03):
            g.box((0.0715, 0.1, 0.004), (0.012, -0.095, z), M.olive(), bevel=0.001)           # 压筋
        g.box((0.04, 0.006, 0.008), (0.012, -0.03, BOX_Z + 0.03), M.steel(), bevel=0.001)     # 提手
        g.box((0.006, 0.02, 0.014), (0.012, -0.05, BOX_Z + 0.053), M.steel(), bevel=0.001)    # 锁扣
        with g.tier(0, 5):
            g.box((0.001, 0.02, 0.05), (0.0475, -0.11, BOX_Z), M.tan(), bevel=0)
        with g.tier(6):
            g.box((0.001, 0.02, 0.05), (0.0475, -0.11, BOX_Z), M.yellow(), bevel=0)
    with g.part("belt"):
        for i in range(6):
            y = -0.045 + i * 0.011
            x = 0.03 - i * 0.004
            g.cyl(0.0042, 0.026, (x, y, BOX_Z - 0.015), M.brass(), seg=10, bevel=0.0004)
            with g.tier(0, 6):
                g.cyl(0.0042, 0.009, (x, y, BOX_Z + 0.011), M.copper(), r2=0.001, seg=10, bevel=0)
            with g.tier(7):
                g.cyl(0.0042, 0.009, (x, y, BOX_Z + 0.011), M.blued(), r2=0.001, seg=10, bevel=0)
            g.box((0.012, 0.004, 0.006), (x, y - 0.0045, BOX_Z - 0.006), M.blued(), bevel=0.0008)

    # ---------------- 固定枪托 ----------------
    g.prof([(-0.05, 0.07), (-0.05, -0.02), (-0.29, -0.08), (-0.32, -0.08), (-0.32, 0.06), (-0.12, 0.07)], 0.042, M.polymer(), bevel=0.007, seg=3)
    g.box((0.048, 0.146, 0.018), (0, -0.01, -0.326), M.rubber(), bevel=0.005)
    g.torus(0.008, 0.002, (0, -0.045, -0.2), M.steel(), seg=16, rseg=6, axis="x")


def info(t: int) -> dict:
    return {
        "gripR": (0, -0.08, -0.022),
        "gripL": (0, 0.0, BZ + 0.12),
        "muzzle": (0, BORE, MZ + 0.06),
        "eject": (0, -0.02, 0.06),
        "sight": (0, RY if t >= 8 else SL, 0.0),
        "eyeRelief": 0.22,
        "slideTravel": 0.03,
        "action": "auto",
    }
