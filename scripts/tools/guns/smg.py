"""蝰蛇冲锋枪。坐标系见 kit.py。

各级外观：0 直弹匣、钢丝托   1 弹匣红色标记   2 弹鼓、带护手前握把、氚光准星   3 实心伸缩托
          4 补偿器   5 散热片 + 发光热管   6 加长枪管   7 双联弹鼓   8 反射式瞄具
"""
import math

from kit import Gun, M

IRON = 0.083     # 机瞄瞄准线
RDOT = 0.102     # 反射式瞄具红点
BORE = 0.026
RAIL = 0.072


def build(g: Gun) -> None:
    # ---------------- 机匣 ----------------
    up = g.prof([(-0.03, -0.012), (0.23, -0.012), (0.23, 0.05), (0.215, 0.064), (-0.02, 0.064), (-0.03, 0.054)], 0.044, M.gunmetal(), bevel=0.004, seg=3)
    g.box((0.012, 0.016, 0.042), (-0.022, 0.034, 0.12), cut=up, bevel=0)                    # 抛壳口
    g.box((0.006, 0.006, 0.12), (0.0225, 0.041, 0.14), cut=up, bevel=0)                     # 拉机柄槽
    g.cyl(0.0085, 0.06, (-0.008, 0.034, 0.09), M.steel(), seg=16)                           # 枪机
    g.rail(0.0, 0.2, RAIL)
    for x in (0.0222, -0.0222):
        g.box((0.0012, 0.004, 0.16), (x, 0.004, 0.11), M.gunmetal(), bevel=0.0005)
    # 下机匣 + 握把
    g.prof([(-0.02, -0.01), (0.12, -0.01), (0.12, -0.024), (0.024, -0.026), (0.006, -0.135), (-0.036, -0.13), (-0.022, -0.03)], 0.034, M.polymer(), bevel=0.005, seg=3)
    g.prof([(0.1, -0.022), (0.1, -0.054, 0.082, -0.054), (0.04, -0.054), (0.02, -0.036), (0.025, -0.034), (0.043, -0.0505), (0.08, -0.0505),
            (0.0965, -0.0505, 0.0965, -0.022)], 0.012, M.polymer(), bevel=0.0008)
    for i in range(7):
        for x in (0.0172, -0.0172):
            g.box((0.0012, 0.0042, 0.026), (x, -0.05 - i * 0.011, -0.008 - i * 0.002), M.rubber(), bevel=0.0005, rot=(0.17, 0, 0))
    g.prof([(0.06, -0.024), (0.065, -0.024), (0.062, -0.04, 0.056, -0.046), (0.053, -0.043), (0.058, -0.034)], 0.006, M.steel(), bevel=0.0008)
    g.pin(0.02, 0.03, 0.0035, 0.022)
    g.pin(0.02, 0.19, 0.0035, 0.022)
    g.box((0.0022, 0.0045, 0.018), (0.0228, 0.0, 0.004), M.steel(), bevel=0.0006, rot=(-0.4, 0, 0))   # 快慢机
    g.box((0.0008, 0.003, 0.003), (0.0226, 0.008, 0.016), M.glow(0xff4030, 1.4), bevel=0)
    g.box((0.026, 0.016, 0.03), (0, -0.018, 0.142), M.gunmetal(), bevel=0.002)                # 弹匣井

    # ---------------- 枪管护套（带散热孔）+ 枪管 ----------------
    sh = g.tube(0.02, 0.0165, 0.18, (0, BORE, 0.23), M.gunmetal(), seg=24)
    for i in range(6):
        z = 0.252 + i * 0.027
        g.cyl(0.0045, 0.06, (-0.03, BORE + 0.007, z), cut=sh, axis="x", seg=12, bevel=0)
        g.cyl(0.0045, 0.03, (0, BORE, z + 0.0135), cut=sh, axis="y", seg=12, bevel=0)
    g.cyl(0.0205, 0.006, (0, BORE, 0.228), M.blued(), seg=24)
    g.cyl(0.0205, 0.006, (0, BORE, 0.406), M.blued(), seg=24)
    for lo, hi, bl in ((0, 5, 0.07), (6, 8, 0.13)):
        with g.tier(lo, hi):
            g.tube(0.0088, 0.0048, bl + 0.18, (0, BORE, 0.23), M.blued(), seg=20)
            mz = 0.41 + bl
            # 4 级：补偿器
            with g.tier(4):
                c = g.tube(0.014, 0.0052, 0.04, (0, BORE, mz), M.blued(), seg=20)
                for i in range(3):
                    g.box((0.019, 0.02, 0.006), (0, BORE + 0.012, mz + 0.01 + i * 0.011), cut=c, bevel=0)
    # 5 级：散热片 + 发光热管
    with g.tier(5):
        for i in range(7):
            g.tube(0.026, 0.0195, 0.003, (0, BORE, 0.25 + i * 0.022), M.steel(), seg=24, bevel=0.0004)
        for x in (0.0235, -0.0235):
            g.box((0.003, 0.003, 0.15), (x, BORE, 0.317), M.glow(0xff8a2a, 2.2), bevel=0)

    # ---------------- 前握把 ----------------
    g.box((0.026, 0.016, 0.05), (0, 0.002, 0.3), M.anodized(), bevel=0.003)
    with g.tier(0, 1):
        g.box((0.028, 0.06, 0.03), (0, -0.036, 0.3), M.polymer(), bevel=0.007, seg=3)
    with g.tier(2):
        g.box((0.03, 0.078, 0.032), (0, -0.044, 0.31), M.polymer(), bevel=0.008, seg=3, rot=(0.08, 0, 0))
        for i in range(4):
            g.box((0.0312, 0.003, 0.03), (0, -0.03 - i * 0.012, 0.31), M.rubber(), bevel=0.0008, rot=(0.08, 0, 0))
        g.box((0.034, 0.006, 0.05), (0, -0.006, 0.312), M.polymer(), bevel=0.002)          # 护手挡板

    # ---------------- 机瞄：准星环 + 照门觇孔 ----------------
    dark = M.blued()
    g.box((0.008, 0.02, 0.012), (0, 0.056, 0.4), dark, bevel=0.0015)
    g.box((0.003, 0.012, 0.004), (0, 0.076, 0.4), dark, bevel=0.0006)
    g.torus(0.0105, 0.0016, (0, IRON, 0.4), dark, seg=28, rseg=8)
    with g.tier(0, 1):
        g.box((0.0065, 0.0065, 0.001), (0, IRON, 0.3965), M.glow(0xff8a2a, 2.6), bevel=0)
    with g.tier(2, 7):
        g.box((0.0065, 0.0065, 0.001), (0, IRON, 0.3965), M.glow(0x9dffa8, 3.2), bevel=0)
    with g.tier(0, 7):
        g.box((0.024, 0.004, 0.014), (0, RAIL + 0.002, 0.012), dark, bevel=0.001)
        g.torus(0.0085, 0.0025, (0, IRON, 0.012), dark, seg=28, rseg=8)
        for x in (0.0125, -0.0125):
            g.box((0.003, 0.02, 0.01), (x, RAIL + 0.01, 0.012), dark, bevel=0.001)
    # 8 级：反射式瞄具（中空框，红点悬在窗口中间）
    with g.tier(8):
        g.box((0.03, 0.006, 0.05), (0, RAIL + 0.003, 0.045), M.anodized(), bevel=0.002)
        for x in (0.0145, -0.0145):
            g.box((0.003, 0.04, 0.04), (x, RAIL + 0.026, 0.05), M.anodized(), bevel=0.0012)
        g.box((0.032, 0.003, 0.04), (0, RAIL + 0.0475, 0.05), M.anodized(), bevel=0.0012)
        g.box((0.005, 0.008, 0.012), (0.0185, RDOT, 0.04), M.rubber(), bevel=0.001)
        g.box((0.0036, 0.0036, 0.001), (0, RDOT, 0.06), M.glow(0xff3020, 4.5), bevel=0)

    # ---------------- 拉机柄（可动） ----------------
    with g.part("bolt"):
        g.box((0.016, 0.006, 0.008), (0.027, 0.041, 0.1), M.steel(), bevel=0.001)
        g.cyl(0.006, 0.012, (0.033, 0.041, 0.1), M.polymer(), axis="x", seg=14)

    # ---------------- 弹匣 / 弹鼓（可动） ----------------
    with g.part("mag", (0, -0.02, 0.14)):
        with g.tier(0, 1):
            g.box((0.024, 0.15, 0.034), (0, -0.095, 0.134), M.gunmetal(), bevel=0.002, rot=(-0.12, 0, 0))
            # 弹匣向前倾 0.12 弧度（底部靠前）：筋、底板、标记都沿弹匣轴线排，z = 0.134 − (y + 0.095) × 0.12
            for i in range(5):
                y = -0.045 - i * 0.026
                g.box((0.0252, 0.004, 0.035), (0, y, 0.134 - (y + 0.095) * 0.12), M.blued(), bevel=0.0008, rot=(-0.12, 0, 0))
            g.box((0.028, 0.012, 0.04), (0, -0.172, 0.1435), M.polymer(), bevel=0.003, rot=(-0.12, 0, 0))
            with g.tier(1):
                g.box((0.0256, 0.012, 0.004), (0, -0.04, 0.1445), M.red(), bevel=0.0008, rot=(-0.12, 0, 0))
        with g.tier(2):
            g.box((0.024, 0.045, 0.03), (0, -0.045, 0.142), M.gunmetal(), bevel=0.002)
            g.cyl(0.062, 0.046, (-0.023, -0.095, 0.15), M.gunmetal(), axis="x", seg=36, bevel=0.003)
            g.cyl(0.064, 0.006, (0.021, -0.095, 0.15), M.steel(), axis="x", seg=36, bevel=0.0015)
            g.cyl(0.018, 0.006, (0.026, -0.095, 0.15), M.blued(), axis="x", seg=20)
            g.box((0.004, 0.004, 0.024), (0.033, -0.095, 0.15), M.steel(), bevel=0.001)
            for i in range(10):
                a = math.tau * i / 10
                g.cyl(0.0035, 0.0012, (0.0268, -0.095 + math.sin(a) * 0.045, 0.15 + math.cos(a) * 0.045), M.hole(), axis="x", seg=10, bevel=0)
            with g.tier(7):
                g.cyl(0.062, 0.032, (-0.058, -0.095, 0.15), M.gunmetal(), axis="x", seg=36, bevel=0.003)
                g.cyl(0.03, 0.004, (-0.061, -0.095, 0.15), M.steel(), axis="x", seg=24)

    # ---------------- 枪托：钢丝折叠托，3 级换实心伸缩托 ----------------
    with g.tier(0, 2):
        for x in (0.014, -0.014):
            g.rod((x, 0.03, -0.03), (x, 0.0, -0.25), 0.004, M.blued())
        g.rod((0.014, -0.004, -0.25), (-0.014, -0.004, -0.25), 0.004, M.blued())
        g.box((0.034, 0.075, 0.01), (0, -0.004, -0.255), M.rubber(), bevel=0.003)
    with g.tier(3):
        st = g.prof([(-0.03, 0.05), (-0.03, -0.02), (-0.22, -0.05), (-0.25, -0.05), (-0.25, 0.05)], 0.03, M.polymer(), bevel=0.005, seg=3)
        g.prof([(-0.08, 0.03), (-0.08, -0.008), (-0.19, -0.028), (-0.19, 0.03)], 0.06, cut=st, bevel=0)
        g.box((0.036, 0.11, 0.016), (0, -0.002, -0.256), M.rubber(), bevel=0.005)


def info(t: int) -> dict:
    mz = 0.41 + (0.13 if t >= 6 else 0.07)
    return {
        "gripR": (0, -0.07, -0.014),
        "gripL": (0, -0.07, 0.31),
        "muzzle": (0, BORE, mz + (0.04 if t >= 4 else 0)),
        "eject": (-0.024, 0.034, 0.12),
        "sight": (0, RDOT, 0.06) if t >= 8 else (0, IRON, 0.012),
        "eyeRelief": 0.2,
        "slideTravel": 0.03,
        "action": "auto",
    }
