"""M9 手枪。坐标系见 kit.py。

各级外观：0 基础   1 加长套筒 + 补偿器、前防滑纹   2 加长弹匣、氚光瞄具   3 竞赛击锤
          4 喇叭口弹匣井   5 银色套筒 + 红点镜   6 套筒减重窗   7 金色扳机   8 战术灯
"""
from kit import Gun, M

DOT = 0.0745     # 机械瞄具三个点的高度（瞄准线）
RDOT = 0.087     # 红点高度
BORE = 0.046
LEAN = 0.171     # 握把 / 弹匣后倾角


def slide(g: Gun, L: float, mat, windows: bool) -> None:
    with g.part("slide"):
        s = g.prof([(-0.04, 0.031), (L, 0.031), (L, 0.058), (L - 0.012, 0.07), (-0.034, 0.07), (-0.04, 0.062)], 0.03, mat, bevel=0.0025, seg=3)
        # 抛壳口：真的挖开，里面是枪管后端和一点黄铜
        g.box((0.017, 0.014, 0.034), (-0.008, 0.066, 0.04), cut=s, bevel=0)
        if windows:
            for i in range(3):
                g.box((0.011, 0.012, 0.015), (0, 0.068, 0.088 + i * 0.024), cut=s, bevel=0)
        g.cyl(0.0072, L - 0.02, (0, 0.05, 0.012), M.steel(), seg=18)
        g.cyl(0.0046, 0.014, (-0.002, 0.052, 0.024), M.brass(), seg=12)
        # 防滑纹：后部，加长套筒前部也有
        g.serrations(0.0152, 0.034, 0.064, -0.032, 7, 0.0058, M.blued())
        if L > 0.19:
            g.serrations(0.0152, 0.036, 0.058, L - 0.046, 5, 0.0058, M.blued())
        g.box((0.005, 0.01, 0.016), (0.0165, 0.052, -0.022), M.blued(), bevel=0.0012)   # 保险
        # 枪口：枪管（空心）+ 复进簧导杆
        g.tube(0.0066, 0.0045, 0.012, (0, BORE, L - 0.004), M.blued(), seg=20)
        g.cyl(0.0032, 0.003, (0, 0.036, L - 0.001), M.steel(), seg=12)
        # 三点式机瞄：照门两只耳朵 + 准星，点在同一高度
        dark = M.blued()
        for x in (0.0083, -0.0083):
            g.box((0.0094, 0.008, 0.008), (x, 0.074, -0.026), dark, bevel=0.0008)
        g.box((0.0052, 0.008, 0.008), (0, 0.074, L - 0.022), dark, bevel=0.0008)
        for lo, hi, rear, front in ((0, 1, M.glow(0xf2f2e6, 1.1), M.glow(0xff8a2a, 2.6)), (2, 8, M.glow(0x7dff8a, 2.4), M.glow(0x9dffa8, 3.2))):
            with g.tier(lo, hi):
                for x in (0.0083, -0.0083):
                    g.box((0.0028, 0.0028, 0.001), (x, DOT, -0.0305), rear, bevel=0)
                g.box((0.0038, 0.0038, 0.001), (0, DOT, L - 0.0265), front, bevel=0)
        # 1 级：补偿器
        with g.tier(1):
            c = g.box((0.028, 0.032, 0.03), (0, 0.047, L + 0.016), M.blued(), bevel=0.004, seg=3)
            g.cyl(0.0052, 0.04, (0, BORE, L - 0.002), cut=c, seg=16, bevel=0)
            for i in range(2):
                g.box((0.013, 0.02, 0.006), (0, 0.062, L + 0.01 + i * 0.011), cut=c, bevel=0)
        # 5 级：红点镜（中空框）
        with g.tier(5):
            g.box((0.026, 0.006, 0.036), (0, 0.073, 0.0), M.anodized(), bevel=0.002)
            for x in (0.0112, -0.0112):
                g.box((0.0034, 0.02, 0.008), (x, 0.086, 0.014), M.anodized(), bevel=0.001)
            g.box((0.0258, 0.0034, 0.008), (0, 0.0975, 0.014), M.anodized(), bevel=0.001)
            g.box((0.0018, 0.0018, 0.001), (0, RDOT, 0.012), M.glow(0xff3020, 4), bevel=0)


def build(g: Gun) -> None:
    # ---------------- 枪身 ----------------
    g.prof([(-0.036, 0.03), (0.152, 0.03), (0.152, 0.008), (0.09, 0.004), (0.03, 0.002), (0.024, -0.012), (0.004, -0.128), (-0.046, -0.124),
            (-0.034, -0.012), (-0.05, 0.014, -0.04, 0.026)], 0.028, M.polymer(), bevel=0.003, seg=3)
    # 扳机护圈（单独的细环）
    g.prof([(0.093, 0.004), (0.093, -0.043, 0.072, -0.043), (0.04, -0.043), (0.02, -0.024), (0.025, -0.022), (0.042, -0.0395), (0.072, -0.0395),
            (0.0895, -0.0395, 0.0895, 0.004)], 0.012, M.polymer(), bevel=0.0008)
    # 握片 + 横向防滑纹 + 螺丝
    g.prof([(0.016, -0.018), (0.0, -0.112), (-0.038, -0.108), (-0.03, -0.02)], 0.034, M.rubber(), bevel=0.004, seg=3)
    for i in range(8):
        for x in (0.0172, -0.0172):
            g.box((0.0012, 0.004, 0.026), (x, -0.03 - i * 0.0105, -0.008 - i * 0.0018), M.polymer(), bevel=0.0005, rot=(LEAN - 0.03, 0, 0))
    g.pin(-0.1, -0.02, 0.003, 0.0172)
    g.pin(-0.028, -0.01, 0.003, 0.0172)
    # 扳机（7 级金色）
    for lo, hi, mat in ((0, 6, M.steel()), (7, 8, M.brass())):
        with g.tier(lo, hi):
            g.prof([(0.052, 0.0), (0.058, 0.0), (0.057, -0.02, 0.05, -0.03), (0.047, -0.028), (0.052, -0.014)], 0.007, mat, bevel=0.0008)
    g.box((0.004, 0.006, 0.026), (0.016, 0.025, 0.03), M.gunmetal(), bevel=0.001)          # 空仓挂机柄
    g.cyl(0.005, 0.003, (0.0135, 0.018, 0.075), M.gunmetal(), axis="x", seg=14)             # 拆卸杆
    g.box((0.004, 0.008, 0.008), (0.015, -0.004, 0.022), M.gunmetal(), bevel=0.001)         # 弹匣释放钮
    for i in range(3):
        g.box((0.03, 0.004, 0.005), (0, 0.008, 0.11 + i * 0.012), M.anodized(), bevel=0.0008)  # 附件导轨
    # 击锤：3 级换镂空竞赛击锤
    with g.tier(0, 2):
        g.box((0.008, 0.02, 0.011), (0, 0.04, -0.047), M.blued(), bevel=0.002, rot=(-0.35, 0, 0))
    with g.tier(3):
        h = g.box((0.006, 0.026, 0.012), (0, 0.042, -0.048), M.steel(), bevel=0.0015, rot=(-0.4, 0, 0))
        g.cyl(0.0032, 0.02, (-0.01, 0.045, -0.049), cut=h, axis="x", seg=12, bevel=0)
    # 4 级：喇叭口弹匣井
    with g.tier(4):
        g.box((0.036, 0.012, 0.056), (0, -0.126, -0.022), M.gunmetal(), bevel=0.004, rot=(LEAN, 0, 0))
    # 8 级：战术灯
    with g.tier(8):
        g.box((0.028, 0.024, 0.05), (0, -0.008, 0.125), M.anodized(), bevel=0.005, seg=3)
        g.cyl(0.0125, 0.008, (0, -0.008, 0.148), M.blued(), seg=20)
        g.cyl(0.0105, 0.001, (0, -0.008, 0.1562), M.glow(0xfff6d8, 2.2), seg=20, bevel=0)

    # ---------------- 套筒（可动） ----------------
    with g.tier(0, 0):
        slide(g, 0.185, M.gunmetal(), False)
    with g.tier(1, 4):
        slide(g, 0.2, M.gunmetal(), False)
    with g.tier(5, 5):
        slide(g, 0.2, M.steel(), False)
    with g.tier(6):
        slide(g, 0.2, M.steel(), True)

    # ---------------- 弹匣（可动；2 级加长） ----------------
    with g.part("mag", (0, -0.12, -0.02)):
        g.box((0.02, 0.11, 0.032), (0, -0.075, -0.014), M.gunmetal(), bevel=0.002, rot=(LEAN, 0, 0))
        g.cyl(0.0045, 0.022, (0, -0.02, -0.014), M.brass(), seg=12)
        with g.tier(0, 1):
            g.box((0.03, 0.012, 0.046), (0, -0.133, -0.024), M.polymer(), bevel=0.003, rot=(LEAN, 0, 0))
        with g.tier(2):
            g.box((0.022, 0.026, 0.034), (0, -0.142, -0.0255), M.gunmetal(), bevel=0.002, rot=(LEAN, 0, 0))
            g.box((0.03, 0.012, 0.046), (0, -0.16, -0.0285), M.polymer(), bevel=0.003, rot=(LEAN, 0, 0))


def info(t: int) -> dict:
    L = 0.2 if t >= 1 else 0.185
    return {
        "gripR": (0, -0.07, -0.014),
        "gripL": (0.026, -0.08, 0.008),
        "muzzle": (0, BORE, L + (0.032 if t >= 1 else 0.01)),
        "eject": (-0.01, 0.07, 0.04),
        "sight": (0, RDOT if t >= 5 else DOT, -0.03),
        "eyeRelief": 0.3,
        "slideTravel": 0.03,
        "action": "semi",
    }
