"""铁壁突击步枪（AR 式）。坐标系见 kit.py：原点在后握把，枪口 +Z，上 +Y，玩家看到的是 +X 一侧。

各级外观（和 src/game/data/weapons.ts 的升级路线对应）：
  0 机械瞄具（觇孔 + 准星柱）   1 准星护翼   2 外露导气管、氚光准星   3 制退器、黑色弹匣
  4 加长弹匣、反射式瞄具        5 四倍镜、前握把   6 加长护木和重枪管   8 激光指示器
"""
from kit import Gun, M

AIM = 0.088          # 机械瞄具 / 红点的瞄准线高度
BORE = 0.028         # 枪管轴线高度
RAIL = 0.066         # 导轨齿顶


def front(g: Gun, hg: float) -> None:
    """护木 + 枪管 + 准星座，hg = 护木长度。"""
    z0 = 0.192
    # 护木：八角截面的铝合金管，三面开 M-LOK 槽
    body = g.box((0.05, 0.052, hg), (0, BORE - 0.002, z0 + hg / 2), M.anodized(), bevel=0.011, seg=3)
    n = int((hg - 0.04) / 0.04)
    for i in range(n):
        z = z0 + 0.04 + i * 0.04
        for x in (0.026, -0.026):
            g.box((0.012, 0.007, 0.026), (x, BORE, z), cut=body, bevel=0)
        g.box((0.007, 0.012, 0.026), (0, BORE - 0.03, z), cut=body, bevel=0)
    # 斜向 45° 的减重孔（上半部）
    for i in range(n):
        z = z0 + 0.04 + i * 0.04
        for x in (0.0185, -0.0185):
            g.cyl(0.0042, 0.02, (x - (0.01 if x > 0 else -0.01), BORE + 0.0185, z), cut=body, axis="x", seg=12, bevel=0,
                  rot=(0, 0, 0))
    g.rail(z0, hg, RAIL)
    # 护木前后端的固定环
    g.box((0.052, 0.054, 0.008), (0, BORE - 0.002, z0 + 0.004), M.gunmetal(), bevel=0.011, seg=3)
    for x in (0.0262, -0.0262):
        g.cyl(0.0028, 0.0012, (x - (0 if x > 0 else 0.0012), BORE - 0.014, z0 + 0.012), M.steel(), axis="x", seg=10, bevel=0.0003)
        g.cyl(0.0028, 0.0012, (x - (0 if x > 0 else 0.0012), BORE - 0.014, z0 + 0.026), M.steel(), axis="x", seg=10, bevel=0.0003)
    # 枪管：护木里一截粗的，伸出来的一截带台阶
    end = z0 + hg
    g.cyl(0.0098, hg, (0, BORE, z0), M.blued(), seg=20)
    g.lathe([(0.0098, 0), (0.0098, 0.03), (0.0088, 0.034), (0.0088, 0.085), (0.0075, 0.089), (0.0075, 0.12)], (0, BORE, end), M.blued(), seg=24)
    # 导气箍（护木里看得到一点）
    g.box((0.02, 0.024, 0.022), (0, BORE + 0.004, end - 0.03), M.gunmetal(), bevel=0.003)


def muzzle(g: Gun, z: float, brake: bool) -> float:
    """枪口装置，返回枪口最前端的 z。"""
    if brake:
        # 制退器：方形截面，两侧各三个大泄气口
        b = g.lathe([(0.0075, 0), (0.0155, 0.004), (0.0165, 0.012), (0.0165, 0.056), (0.014, 0.062), (0.0062, 0.062), (0.0062, 0)],
                    (0, BORE, z), M.blued(), seg=24, closed=True)
        for i in range(3):
            g.box((0.05, 0.011, 0.009), (0, BORE, z + 0.018 + i * 0.014), cut=b, bevel=0)
        return z + 0.062
    # 鸟笼消焰器：六条纵向槽
    b = g.lathe([(0.0075, 0), (0.0112, 0.003), (0.0112, 0.04), (0.0098, 0.045), (0.0058, 0.045), (0.0058, 0)], (0, BORE, z), M.blued(), seg=24, closed=True)
    import math
    for i in range(5):
        a = math.tau * (i + 0.5) / 6 + math.pi / 2  # 底部不开槽（真的鸟笼也这样，防止扬尘）
        g.box((0.0034, 0.012, 0.024), (math.cos(a) * 0.0105, BORE + math.sin(a) * 0.0105, z + 0.024), cut=b, bevel=0, rot=(0, 0, a - math.pi / 2))
    return z + 0.045


def build(g: Gun) -> None:
    # ---------------- 上机匣 ----------------
    up = g.prof([(-0.045, 0.004), (0.192, 0.004), (0.192, 0.056), (-0.03, 0.056), (-0.045, 0.046)], 0.042, M.gunmetal(), bevel=0.004, seg=3)
    # 抛壳口（右侧，-X）：真的挖进去，能看到里面的枪机
    g.box((0.012, 0.017, 0.056), (-0.021, 0.026, 0.118), cut=up, bevel=0)
    g.cyl(0.0085, 0.07, (-0.006, 0.027, 0.085), M.steel(), seg=18)              # 枪机
    g.box((0.0022, 0.019, 0.058), (-0.0222, 0.014, 0.118), M.gunmetal(), bevel=0.0006, rot=(0, 0, 0.5))  # 翻开的防尘盖
    g.prof([(0.062, 0.02), (0.085, 0.02), (0.085, 0.04, 0.062, 0.044)], 0.008, M.gunmetal(), bevel=0.0015, x=-0.024)  # 抛壳挡板
    g.cyl(0.0058, 0.016, (-0.027, 0.036, 0.034), M.gunmetal(), rot=(0, -0.5, 0), seg=14)  # 助推器
    g.cyl(0.0048, 0.004, (-0.0345, 0.036, 0.022), M.steel(), rot=(0, -0.5, 0), seg=14)
    g.rail(-0.03, 0.222, RAIL)
    # 上机匣两侧的凸筋（造型线）
    for x in (0.0212, -0.0212):
        g.box((0.0012, 0.004, 0.12), (x, 0.048, 0.1), M.gunmetal(), bevel=0.0005)

    # ---------------- 下机匣 ----------------
    low = g.prof([(-0.045, 0.006), (0.185, 0.006), (0.185, -0.028), (0.16, -0.034), (0.156, -0.068), (0.106, -0.072),
                  (0.102, -0.034), (0.022, -0.034),
                  (-0.01, -0.04), (-0.032, -0.03), (-0.045, -0.018)], 0.038, M.gunmetal(), bevel=0.003, seg=3)
    # 扳机护圈：一条单独的细环（不靠布尔挖孔），扳机从环里露出来
    g.prof([(0.1, -0.033), (0.1, -0.057, 0.084, -0.057), (0.03, -0.057), (0.018, -0.04), (0.023, -0.04), (0.033, -0.0535),
            (0.082, -0.0535), (0.0965, -0.0535, 0.0965, -0.033)], 0.012, M.gunmetal(), bevel=0.0008)
    # 弹匣井内腔（从下面看是空的）
    g.box((0.026, 0.05, 0.044), (0, -0.06, 0.131), cut=low, bevel=0, rot=(0.06, 0, 0))
    # 扳机、快慢机、弹匣释放钮、空仓挂机、销子
    g.prof([(0.062, -0.028), (0.066, -0.028), (0.062, -0.044, 0.056, -0.047), (0.054, -0.044), (0.058, -0.036)], 0.006, M.steel(), bevel=0.0008)
    g.cyl(0.005, 0.003, (0.019, -0.012, 0.012), M.steel(), axis="x", seg=14)
    g.box((0.0022, 0.0045, 0.02), (0.0222, -0.012, 0.022), M.steel(), bevel=0.0006, rot=(-0.5, 0, 0))
    g.box((0.0008, 0.0026, 0.0026), (0.0196, -0.004, 0.03), M.red(), bevel=0)
    g.box((0.003, 0.011, 0.011), (-0.0205, -0.024, 0.097), M.steel(), bevel=0.001)
    g.box((0.003, 0.02, 0.012), (0.0205, -0.004, 0.128), M.gunmetal(), bevel=0.001)
    g.box((0.003, 0.008, 0.016), (0.0215, 0.004, 0.128), M.gunmetal(), bevel=0.001)
    g.pin(-0.01, -0.005, 0.0032, 0.019)
    g.pin(-0.006, 0.168, 0.0032, 0.019)
    g.pin(-0.022, 0.058, 0.002, 0.019)
    g.pin(-0.014, 0.036, 0.002, 0.019)

    # ---------------- 握把 ----------------
    grip = g.prof([(0.022, -0.036), (0.012, -0.06), (0.002, -0.138), (-0.04, -0.134), (-0.03, -0.07), (-0.036, -0.04), (-0.02, -0.032)],
                  0.032, M.polymer(), bevel=0.006, seg=3)
    del grip
    # 握把两侧的防滑纹、背部的指槽纹
    # 纹路垂直于握把轴线（握把向后倾约 7°），长度留在握把前后缘以内
    for i in range(7):
        for x in (0.0162, -0.0162):
            g.box((0.0012, 0.0042, 0.024), (x, -0.056 - i * 0.011, -0.010 - i * 0.0012), M.rubber(), bevel=0.0005, rot=(0.13, 0, 0))
    g.box((0.026, 0.006, 0.036), (0, -0.139, -0.019), M.rubber(), bevel=0.002, rot=(-0.1, 0, 0))

    # ---------------- 拉机柄（可动） ----------------
    with g.part("bolt"):
        g.box((0.012, 0.007, 0.06), (0, 0.0585, -0.02), M.gunmetal(), bevel=0.0015)
        g.prof([(-0.058, 0.055), (-0.044, 0.055), (-0.044, 0.063), (-0.058, 0.063)], 0.046, M.gunmetal(), bevel=0.002)
        g.box((0.008, 0.006, 0.01), (0.021, 0.059, -0.05), M.steel(), bevel=0.001)

    # ---------------- 枪托：缓冲管 + 伸缩托 ----------------
    g.cyl(0.0145, 0.17, (0, 0.03, -0.215), M.anodized(), seg=22)
    g.cyl(0.0175, 0.012, (0, 0.03, -0.057), M.gunmetal(), seg=22)                      # 城堡螺母
    for i in range(6):
        import math
        a = math.tau * i / 6
        g.box((0.004, 0.004, 0.012), (math.cos(a) * 0.0175, 0.03 + math.sin(a) * 0.0175, -0.051), M.gunmetal(), bevel=0.0008, rot=(0, 0, a))
    g.box((0.006, 0.024, 0.006), (0, 0.004, -0.06), M.gunmetal(), bevel=0.0015)        # 背带环座
    stock = g.prof([(-0.115, 0.05), (-0.115, 0.008), (-0.15, -0.002), (-0.255, -0.062), (-0.305, -0.07), (-0.305, 0.052), (-0.2, 0.056)],
                   0.036, M.polymer(), bevel=0.006, seg=3)
    g.prof([(-0.165, 0.0), (-0.25, -0.048), (-0.285, -0.052), (-0.285, 0.0)], 0.06, cut=stock, bevel=0)   # 镂空
    g.box((0.04, 0.128, 0.014), (0, -0.009, -0.311), M.rubber(), bevel=0.004)          # 托底板
    for i in range(6):
        g.box((0.041, 0.003, 0.0145), (0, -0.06 + i * 0.02, -0.3115), M.polymer(), bevel=0.0008)
    g.box((0.012, 0.01, 0.03), (0, -0.004, -0.165), M.steel(), bevel=0.002)             # 调节扳手
    g.box((0.03, 0.006, 0.07), (0, 0.057, -0.2), M.rubber(), bevel=0.002)               # 贴腮垫

    # ---------------- 护木、枪管、枪口（6 级加长） ----------------
    for lo, hi, hg in ((0, 5, 0.27), (6, 8, 0.33)):
        with g.tier(lo, hi):
            front(g, hg)
            end = 0.192 + hg + 0.12
            with g.tier(0, 2):
                muzzle(g, end, False)
            with g.tier(3):
                muzzle(g, end, True)
            # 2 级：外露的导气管
            with g.tier(2):
                g.cyl(0.0034, hg - 0.03, (0, BORE + 0.0215, 0.192), M.steel(), seg=12)
            sights(g, 0.192 + hg - 0.025)
            # 5 级：前握把
            with g.tier(5):
                fz = 0.192 + hg * 0.42
                g.prof([(fz - 0.016, -0.004), (fz + 0.016, -0.004), (fz + 0.013, -0.02), (fz + 0.011, -0.086), (fz - 0.013, -0.086), (fz - 0.015, -0.02)],
                       0.028, M.polymer(), bevel=0.006, seg=3)
                for i in range(5):
                    g.box((0.0292, 0.003, 0.025), (0, -0.03 - i * 0.011, fz - 0.001), M.rubber(), bevel=0.0008)
                g.box((0.026, 0.008, 0.04), (0, -0.002, fz), M.anodized(), bevel=0.002)
            # 8 级：激光指示器（左侧导轨）
            with g.tier(8):
                lz = 0.192 + hg - 0.07
                g.box((0.02, 0.022, 0.058), (0.037, BORE + 0.002, lz), M.anodized(), bevel=0.003)
                g.cyl(0.0052, 0.004, (0.037, BORE + 0.006, lz + 0.029), M.blued(), seg=14)
                g.cyl(0.0034, 0.0012, (0.037, BORE + 0.006, lz + 0.0325), M.glow(0xff2a1a, 4), seg=12, bevel=0)
                g.box((0.006, 0.004, 0.012), (0.037, BORE + 0.0145, lz - 0.01), M.rubber(), bevel=0.001)

    # ---------------- 弹匣（可动；4 级加长，3 级起黑色聚合物） ----------------
    for lo, hi, h, mat in ((0, 2, 0.15, M.gunmetal()), (3, 3, 0.15, M.polymer()), (4, 8, 0.19, M.polymer())):
        with g.tier(lo, hi), g.part("mag", (0, -0.06, 0.13)):
            # 略带弧度的弹匣：侧面轮廓前后两条弧线
            top, bot = -0.03, -0.03 - h
            g.prof([(0.108, top), (0.154, top), (0.168, (top + bot) / 2, 0.176, bot), (0.126, bot - 0.004), (0.118, (top + bot) / 2, 0.108, top)],
                   0.0235, mat, bevel=0.002)
            for i in range(4):
                y = top - 0.03 - i * (h - 0.05) / 3.5
                zf = 0.156 + (0.02 * ((top - y) / h) ** 1.6)
                g.box((0.0245, 0.0032, 0.04), (0, y, zf - 0.024), mat, bevel=0.0008, rot=(0.1 + 0.1 * i, 0, 0))
            g.box((0.027, 0.01, 0.05), (0, bot - 0.004, 0.151), M.rubber(), bevel=0.003, rot=(0.34, 0, 0))
            # 最上面一发子弹（换弹时看得见）
            g.cyl(0.0048, 0.036, (0, top + 0.003, 0.112), M.brass(), seg=12)
            g.cyl(0.0048, 0.012, (0, top + 0.003, 0.148), M.copper(), r2=0.0012, seg=12)


def sights(g: Gun, front_z: float) -> None:
    """瞄具：0–3 级机械瞄具，4 级反射式，5 级起四倍镜。"""
    dark = M.blued()
    # ---- 机械瞄具（0–3 级）----
    with g.tier(0, 3):
        rz = -0.01
        g.box((0.026, 0.007, 0.026), (0, RAIL + 0.0015, rz), M.anodized(), bevel=0.0015)
        g.box((0.005, 0.012, 0.005), (0, RAIL + 0.011, rz), dark, bevel=0.0008)
        g.torus(0.0046, 0.0012, (0, AIM, rz), dark, seg=24, rseg=8)                      # 觇孔（鬼环）
        for x in (0.0098, -0.0098):
            g.prof([(rz - 0.006, RAIL + 0.004), (rz + 0.006, RAIL + 0.004), (rz + 0.004, AIM + 0.005), (rz - 0.004, AIM + 0.005)], 0.0026, dark, bevel=0.0008, x=x)
        # 准星：座 + 细柱，柱顶是发光点
        g.box((0.016, 0.007, 0.018), (0, RAIL + 0.0015, front_z), M.anodized(), bevel=0.0015)
        g.box((0.0036, AIM - RAIL - 0.004, 0.0036), (0, (AIM + RAIL) / 2 + 0.001, front_z), dark, bevel=0.0006)
        with g.tier(0, 1):
            g.box((0.0075, 0.0075, 0.0012), (0, AIM, front_z - 0.003), M.glow(0xffa040, 3.6), bevel=0)
        with g.tier(2, 3):
            g.box((0.006, 0.006, 0.0012), (0, AIM, front_z - 0.003), M.glow(0x9dffa8, 3.2), bevel=0)
        with g.tier(1, 3):
            for x in (0.0092, -0.0092):
                g.prof([(front_z - 0.006, RAIL + 0.004), (front_z + 0.006, RAIL + 0.004), (front_z + 0.003, AIM + 0.006), (front_z - 0.003, AIM + 0.006)],
                       0.0024, dark, bevel=0.0008, x=x)
    # ---- 反射式瞄具（4 级）：中空的框，红点悬在窗口正中 ----
    with g.tier(4, 4):
        z0, ln = 0.002, 0.046
        g.box((0.032, 0.008, ln), (0, RAIL + 0.004, z0), M.anodized(), bevel=0.002)
        for x in (0.0146, -0.0146):
            g.box((0.0032, 0.03, ln), (x, RAIL + 0.021, z0), M.anodized(), bevel=0.0012)
        g.box((0.0324, 0.0034, ln), (0, RAIL + 0.0375, z0), M.anodized(), bevel=0.0012)
        g.box((0.0045, 0.008, 0.012), (0.0185, AIM, z0 - 0.006), M.rubber(), bevel=0.001)       # 亮度钮
        g.cyl(0.0048, 0.006, (-0.019, AIM - 0.008, z0 + 0.006), M.gunmetal(), axis="x", seg=12)  # 电池仓
        g.cyl(0.0011, 0.0012, (0, AIM, z0 + ln / 2 - 0.006), M.glow(0xff3020, 5), seg=10, bevel=0)
        g.torus(0.0062, 0.00035, (0, AIM, z0 + ln / 2 - 0.006), M.glow(0xff3a28, 2.4), seg=32, rseg=4)
        g.box((0.012, 0.004, 0.018), (0, RAIL + 0.002, front_z), M.anodized(), bevel=0.001)       # 折倒的准星
    # ---- 四倍镜（5 级起）----
    with g.tier(5):
        sy = 0.106
        g.lathe([(0.0, -0.05), (0.0205, -0.05), (0.0205, -0.034), (0.0145, -0.022), (0.0145, 0.058), (0.0235, 0.082), (0.0235, 0.112), (0.021, 0.114),
                 (0.021, 0.106), (0.0, 0.106)], (0, sy, 0.04), M.anodized(), seg=32)
        g.cyl(0.02, 0.001, (0, sy, 0.1452), M.lens(), seg=32, bevel=0)                           # 物镜
        g.cyl(0.0175, 0.001, (0, sy, -0.0106), M.lens(), seg=32, bevel=0)                        # 目镜
        g.lathe([(0.0, 0), (0.0095, 0), (0.0095, 0.011), (0.0085, 0.013), (0.0, 0.013)], (0, sy + 0.0145, 0.06), M.anodized(), axis="y", seg=20)
        g.lathe([(0.0, 0), (0.0095, 0), (0.0095, 0.011), (0.0085, 0.013), (0.0, 0.013)], (0.0145, sy, 0.06), M.anodized(), axis="x", seg=20)
        g.torus(0.0215, 0.0016, (0, sy, -0.002), M.rubber(), seg=32, rseg=8)                     # 调焦环（套在目镜筒上）
        for z in (0.004, 0.096):
            g.box((0.02, sy - RAIL - 0.014, 0.016), (0, (sy + RAIL - 0.014) / 2, z), M.anodized(), bevel=0.002)
            g.torus(0.0165, 0.0036, (0, sy, z), M.anodized(), seg=28, rseg=8)
            g.cyl(0.0022, 0.004, (0.0135, RAIL + 0.004, z), M.steel(), axis="x", seg=10)


def info(t: int) -> dict:
    hg = 0.33 if t >= 6 else 0.27
    end = 0.192 + hg + 0.12
    if t >= 5:
        sight, relief = (0, 0.106, -0.01), 0.1
    elif t >= 4:
        sight, relief = (0, AIM, 0.002 - 0.023), 0.17
    else:
        sight, relief = (0, AIM, -0.01), 0.12
    return {
        "gripR": (0, -0.075, -0.02),
        "gripL": (0, -0.012, 0.192 + hg * 0.42) if t >= 5 else (0, -0.012, 0.192 + hg * 0.5),
        "muzzle": (0, BORE, end + (0.062 if t >= 3 else 0.045)),
        "eject": (-0.024, 0.026, 0.118),
        "sight": sight,
        "eyeRelief": relief,
        "slideTravel": 0.04,
        "action": "auto",
    }
