"""寒鸦狙击步枪（栓动）。坐标系见 kit.py。

各级外观：0 基础   1 两脚架张开   2 加长弹匣   3 镜头遮光罩   5 激光测距仪   6 橄榄绿底盘   8 消音器
"""
import math

from kit import Gun, M

BORE = 0.046
SY = 0.112       # 瞄准镜光轴
BZ = 0.66        # 制退器起点


def chassis(g: Gun, mat) -> None:
    body = g.prof([(-0.06, 0.03), (0.4, 0.03), (0.4, -0.02), (0.38, -0.03), (0.17, -0.03), (0.15, -0.04), (0.1, -0.04), (0.09, -0.03), (0.02, -0.03),
                   (0.018, -0.044), (-0.004, -0.145), (-0.046, -0.14), (-0.034, -0.03), (-0.06, -0.02)], 0.05, mat, bevel=0.006, seg=3)
    for i in range(4):
        g.box((0.07, 0.016, 0.036), (0, -0.008, 0.2 + i * 0.05), cut=body, bevel=0)           # 前托减重孔
    g.prof([(0.09, -0.03), (0.09, -0.058, 0.072, -0.058), (0.034, -0.058), (0.016, -0.044), (0.021, -0.042), (0.036, -0.0545), (0.07, -0.0545),
            (0.0865, -0.0545, 0.0865, -0.03)], 0.012, mat, bevel=0.0008)
    # 骨架枪托
    st = g.prof([(-0.06, 0.03), (-0.06, -0.03), (-0.3, -0.08), (-0.34, -0.08), (-0.34, 0.07), (-0.12, 0.07), (-0.1, 0.03)], 0.036, mat, bevel=0.005, seg=3)
    g.prof([(-0.12, 0.01), (-0.12, -0.02), (-0.27, -0.055), (-0.27, 0.01)], 0.06, cut=st, bevel=0)


def build(g: Gun) -> None:
    with g.tier(0, 5):
        chassis(g, M.polymer())
    with g.tier(6):
        chassis(g, M.olive())
    for i in range(6):
        for x in (0.0252, -0.0252):
            g.box((0.0012, 0.0042, 0.028), (x, -0.06 - i * 0.012, -0.014 - i * 0.0026), M.rubber(), bevel=0.0005, rot=(0.2, 0, 0))
    g.prof([(0.05, -0.03), (0.055, -0.03), (0.052, -0.046, 0.046, -0.052), (0.043, -0.049), (0.048, -0.04)], 0.006, M.steel(), bevel=0.0008)
    g.pin(0.006, 0.0, 0.004, 0.025)
    g.pin(0.006, 0.14, 0.004, 0.025)
    g.box((0.042, 0.016, 0.14), (0, 0.078, -0.24), M.rubber(), bevel=0.006, seg=3)            # 贴腮板
    for z in (-0.2, -0.28):
        g.cyl(0.004, 0.012, (0, 0.062, z), M.steel(), axis="y", seg=10)
    g.box((0.046, 0.16, 0.018), (0, -0.005, -0.346), M.rubber(), bevel=0.005)                 # 托底板
    g.box((0.012, 0.05, 0.012), (0, -0.1, -0.28), M.blued(), bevel=0.002)                     # 单脚架

    # ---------------- 机匣 + 枪管 ----------------
    rc = g.cyl(0.02, 0.2, (0, BORE, -0.04), M.gunmetal(), seg=28)
    g.box((0.014, 0.018, 0.06), (-0.016, BORE + 0.004, 0.06), cut=rc, bevel=0)                # 抛壳口
    g.cyl(0.006, 0.05, (-0.006, BORE, 0.035), M.brass(), seg=14)
    br = g.cyl(0.015, 0.5, (0, BORE, 0.16), M.blued(), seg=28)
    for i in range(6):
        a = math.tau * i / 6
        g.cyl(0.0034, 0.3, (math.cos(a) * 0.0162, BORE + math.sin(a) * 0.0162, 0.33), cut=br, seg=10, bevel=0)   # 减重凹槽
    # 制退器（0–7 级）/ 消音器（8 级）
    with g.tier(0, 7):
        bk = g.lathe([(0.0075, 0), (0.019, 0), (0.019, 0.07), (0.0075, 0.07)], (0, BORE, BZ), M.blued(), seg=24, closed=True)
        for i in range(3):
            g.box((0.05, 0.013, 0.012), (0, BORE, BZ + 0.015 + i * 0.02), cut=bk, bevel=0)
    with g.tier(8):
        g.lathe([(0.0075, 0), (0.024, 0.004), (0.026, 0.02), (0.026, 0.19), (0.022, 0.2), (0.0075, 0.2)], (0, BORE, BZ), M.tan(), seg=28, closed=True)
        for i in range(4):
            g.torus(0.0262, 0.0012, (0, BORE, BZ + 0.04 + i * 0.04), M.rubber(), seg=28, rseg=6)

    # ---------------- 枪栓（可动：绕枪管轴抬起、后拉） ----------------
    with g.part("bolt", (0, BORE, 0.02)):
        g.cyl(0.0118, 0.11, (0, BORE, -0.06), M.steel(), seg=18)
        g.rod((0.0, BORE, 0.03), (0.05, 0.03, 0.02), 0.004, M.steel())
        g.sphere(0.011, (0.054, 0.028, 0.018), M.polymer(), seg=16)

    # ---------------- 弹匣（可动；2 级加长） ----------------
    for lo, hi, h in ((0, 1, 0.05), (2, 8, 0.07)):
        with g.tier(lo, hi), g.part("mag", (0, -0.04, 0.125)):
            g.box((0.03, h, 0.06), (0, -0.03 - h / 2, 0.125), M.gunmetal(), bevel=0.003)
            g.box((0.034, 0.01, 0.064), (0, -0.035 - h, 0.125), M.rubber(), bevel=0.003)

    # ---------------- 瞄准镜 ----------------
    g.lathe([(0, -0.11), (0.022, -0.11), (0.024, -0.09), (0.017, -0.06), (0.017, 0.1), (0.03, 0.15), (0.03, 0.19), (0.027, 0.192), (0.027, 0.18), (0, 0.18)],
            (0, SY, 0.04), M.anodized(), seg=32)
    g.cyl(0.0265, 0.001, (0, SY, 0.2205), M.lens(), seg=32, bevel=0)                          # 物镜
    turret = [(0.0, 0), (0.011, 0), (0.011, 0.014), (0.0095, 0.016), (0.0, 0.016)]
    g.lathe(turret, (0, SY + 0.016, 0.06), M.anodized(), axis="y", seg=20)                    # 高低
    g.lathe(turret, (0.016, SY, 0.06), M.anodized(), axis="x", seg=20)                        # 风偏
    g.cyl(0.006, 0.014, (-0.031, SY, 0.02), M.anodized(), axis="x", seg=14)                   # 视差
    g.torus(0.0225, 0.0018, (0, SY, -0.05), M.rubber(), seg=32, rseg=8)                       # 调焦环
    for z in (-0.01, 0.12):
        g.box((0.03, 0.014, 0.018), (0, 0.072, z), M.anodized(), bevel=0.002)
        g.box((0.014, SY - 0.089, 0.014), (0, (0.07 + SY - 0.019) / 2, z), M.anodized(), bevel=0.002)
        g.torus(0.019, 0.004, (0, SY, z), M.anodized(), seg=28, rseg=8)
    # 目镜：微亮镜片 + 十字分划 + 红点（举镜过程中、镜框遮罩出现之前看得到瞄点）
    ey = SY + 0.012 / 0.95
    g.cyl(0.02, 0.001, (0, SY, -0.0714), M.glow(0x1c3444, 0.7), seg=28, bevel=0)
    half = math.sqrt(0.02 ** 2 - (ey - SY) ** 2)
    g.box((half * 2, 0.0005, 0.0006), (0, ey, -0.0718), M.hole(), bevel=0)
    g.box((0.0005, 0.04, 0.0006), (0, SY, -0.0718), M.hole(), bevel=0)
    g.cyl(0.0011, 0.0008, (0, ey, -0.0728), M.glow(0xff3020, 3.5), seg=10, bevel=0)
    with g.tier(3):
        g.tube(0.031, 0.0285, 0.04, (0, SY, 0.23), M.anodized(), seg=32)                      # 遮光罩
    with g.tier(5):
        g.box((0.024, 0.02, 0.06), (0.03, SY + 0.014, 0.16), M.anodized(), bevel=0.004)       # 测距仪
        g.cyl(0.005, 0.001, (0.03, SY + 0.014, 0.19), M.glow(0xff2a1a, 3), seg=12, bevel=0)

    # ---------------- 两脚架（1 级起张开一点） ----------------
    g.box((0.03, 0.012, 0.03), (0, -0.034, 0.36), M.blued(), bevel=0.002)
    for lo, hi, k in ((0, 0, 1.0), (1, 8, 1.3)):
        with g.tier(lo, hi):
            for x in (0.014, -0.014):
                g.rod((x, -0.036, 0.36), (x * k, -0.04, 0.53), 0.0045, M.steel())
                g.sphere(0.006, (x * k, -0.04, 0.535), M.rubber(), seg=12)


def info(t: int) -> dict:
    return {
        "gripR": (0, -0.08, -0.024),
        "gripL": (0, -0.02, 0.32),
        "muzzle": (0, BORE, BZ + (0.2 if t >= 8 else 0.07)),
        "eject": (-0.022, BORE, 0.06),
        "sight": (0, SY, -0.07),
        "eyeRelief": 0.08,
        "slideTravel": 0.08,
        "action": "bolt",
    }
