import { Vector3 } from 'three';
import { GunKit, brass, dark, glow, hole, outline, pin, poly, side, steel, Z, type GunInfo } from './kit-ext';

/** M9 手枪：套筒（开火后坐）、带护圈的枪身、斜握把、防滑握片、可拆弹匣 */
export function pistol(k: GunKit): GunInfo {
  const { b, t } = k;
  const L = t >= 1 ? 0.2 : 0.185; // 套筒前端
  const slideCol = t >= 5 ? 0x8d949b : 0x4f565e;
  const frame = poly(0x1e2023);

  // ---- 枪身：一体轮廓，护圈是挖出来的洞 ----
  side(
    b,
    outline(
      [
        [-0.034, 0.03],
        [0.152, 0.03],
        [0.152, 0.008],
        [0.09, 0.006],
        [0.088, -0.03, 0.076, -0.041],
        [0.04, -0.043],
        [0.026, -0.03, 0.022, -0.012],
        [0.004, -0.128],
        [-0.046, -0.124],
        [-0.034, -0.012],
        [-0.05, 0.016, -0.034, 0.03],
      ],
      [
        [
          [0.074, 0.0],
          [0.078, -0.028, 0.068, -0.033],
          [0.038, -0.034],
          [0.03, -0.012],
          [0.032, 0.0],
        ],
      ],
    ),
    0.028,
    frame,
    0.003,
  );
  // 握片：比枪身略宽、带防滑纹
  side(
    b,
    outline([
      [0.016, -0.018],
      [0.0, -0.112],
      [-0.038, -0.108],
      [-0.03, -0.02],
    ]),
    0.034,
    poly(0x2a2724),
    0.003,
  );
  for (let i = 0; i < 6; i++) {
    for (let j = 0; j < 3; j++) {
      const y = -0.032 - i * 0.014;
      const z = 0.002 - j * 0.013 - i * 0.0025;
      b.box(0.0015, 0.006, 0.006, { x: 0.0172, y, z }, poly(0x141312, { jitter: 0 }));
    }
  }
  // 握片螺丝、扳机、击锤、空仓挂机柄、拆卸杆、弹匣释放钮
  pin(b, -0.098, -0.02, 0.003, 0.0172, steel(0x8a8e92));
  pin(b, -0.03, -0.012, 0.003, 0.0172, steel(0x8a8e92));
  b.box(0.007, 0.024, 0.006, { y: -0.025, z: 0.054, rx: 0.25 }, t >= 7 ? steel(0xc89a3a) : steel(0x8a8e92));
  b.box(0.012, 0.006, 0.026, { x: 0.016, y: 0.022, z: 0.03 }, steel(0x5a6066)); // 空仓挂机柄
  b.cyl(0.005, 0.005, 0.003, 10, { x: 0.0155, y: 0.016, z: 0.075, rz: Z }, steel(0x5a6066)); // 拆卸杆
  b.box(0.004, 0.008, 0.008, { x: 0.015, y: -0.006, z: 0.022 }, steel(0x6a7076)); // 弹匣释放钮
  // 击锤：3 级起换镂空竞赛击锤
  if (t >= 3) {
    b.box(0.006, 0.02, 0.004, { y: 0.034, z: -0.046, rx: -0.4 }, steel(0xb8bcc0));
    b.box(0.006, 0.004, 0.012, { y: 0.05, z: -0.05, rx: -0.4 }, steel(0xb8bcc0));
  } else {
    b.rbox(0.008, 0.02, 0.012, 0.002, { y: 0.032, z: -0.044, rx: -0.35 }, dark(0x22252a));
  }
  // 导轨（防尘盖下面）
  for (let i = 0; i < 3; i++) b.box(0.03, 0.004, 0.005, { y: 0.0, z: 0.11 + i * 0.012 }, dark(0x15171a));
  // 8 级：战术灯
  if (t >= 8) {
    b.rbox(0.03, 0.026, 0.05, 0.006, { y: -0.022, z: 0.125 }, poly(0x1a1b1d));
    b.cyl(0.011, 0.011, 0.002, 12, { y: -0.009, z: 0.151, rx: Z }, glow(0xfff6d8, 2.2));
  }

  // ---- 套筒（可动） ----
  const s = k.part('slide');
  side(
    s,
    outline([
      [-0.04, 0.03],
      [L, 0.03],
      [L, 0.058],
      [L - 0.012, 0.07],
      [-0.034, 0.07],
      [-0.04, 0.062],
    ]),
    0.03,
    steel(slideCol),
    0.0025,
  );
  // 后部防滑纹（两侧），1 级起前部也有
  for (const x of [0.0152, -0.0152]) {
    for (let i = 0; i < 7; i++) s.box(0.0015, 0.03, 0.0028, { x, y: 0.035, z: -0.032 + i * 0.0058 }, dark(0x1a1c1f, { jitter: 0 }));
    if (t >= 1) for (let i = 0; i < 5; i++) s.box(0.0015, 0.022, 0.0028, { x, y: 0.04, z: L - 0.045 + i * 0.0058 }, dark(0x1a1c1f, { jitter: 0 }));
  }
  // 抛壳口：能看到枪管后端和一点黄铜
  s.box(0.014, 0.002, 0.032, { x: -0.004, y: 0.0695, z: 0.04 }, hole());
  s.box(0.01, 0.003, 0.012, { x: -0.004, y: 0.066, z: 0.034 }, brass());
  // 保险 / 解脱杆（套筒后部，M9 的标志）
  s.box(0.006, 0.01, 0.016, { x: 0.016, y: 0.05, z: -0.024 }, dark(0x2a2d31));
  // 枪管、复进簧导杆
  s.tubeZ(0.0065, 0.012, 14, { y: 0.046, z: L - 0.004 }, dark(0x16181b));
  s.cyl(0.0042, 0.0042, 0.002, 12, { y: 0.046, z: L + 0.0075, rx: Z }, hole());
  // 三点式机瞄：照门是两只"耳朵"中间留真正的缺口（以前缺口只是贴在实心块上的黑色，准星被照门整个挡住），
  // 准星比缺口窄，瞄准时正好卡在缺口里，三个点连成一条线，中间那个点就是弹着点（= 屏幕中心）。
  // 照门点白色、准星点橙色发光，夜里和亮背景前都能看清；2 级起全部换氚光（绿色发光）
  const SIGHT_TOP = 0.0745;
  const DOT_Y = 0.072;
  const sightCol = dark(0x101113, { jitter: 0 });
  for (const x of [0.0083, -0.0083]) s.box(0.0094, 0.009, 0.008, { x, y: SIGHT_TOP - 0.0045, z: -0.026 }, sightCol);
  const rearDot = t >= 2 ? glow(0x7dff8a, 2.4) : glow(0xf2f2e6, 1.1);
  const frontDot = t >= 2 ? glow(0x9dffa8, 3.2) : glow(0xff8a2a, 2.6);
  for (const x of [0.0083, -0.0083]) s.box(0.0028, 0.0028, 0.001, { x, y: DOT_Y, z: -0.0305 }, rearDot);
  // 准星离眼睛远一倍，做得比照门点宽一些，屏幕上看起来大约是缺口的一半宽
  s.box(0.0058, 0.009, 0.008, { y: SIGHT_TOP - 0.0045, z: L - 0.022 }, sightCol);
  s.box(0.0042, 0.0042, 0.001, { y: DOT_Y, z: L - 0.0265 }, frontDot);
  // 1 级：补偿器
  if (t >= 1) {
    s.rbox(0.028, 0.03, 0.03, 0.006, { y: 0.03, z: L + 0.001 }, dark(0x24272b));
    for (let i = 0; i < 2; i++) s.box(0.012, 0.002, 0.005, { y: 0.06, z: L + 0.01 + i * 0.01 }, hole());
  }
  // 6 级：套筒减重开窗
  if (t >= 6) for (let i = 0; i < 3; i++) s.rbox(0.012, 0.002, 0.016, 0.0009, { y: 0.0695, z: 0.085 + i * 0.024 }, hole());
  // 5 级：红点镜（开放式，镜片发光）
  if (t >= 5) {
    s.rbox(0.026, 0.008, 0.036, 0.003, { y: 0.07, z: 0.0 }, poly(0x17181a));
    s.box(0.004, 0.018, 0.03, { x: 0.011, y: 0.076, z: 0.0 }, poly(0x17181a));
    s.box(0.004, 0.018, 0.03, { x: -0.011, y: 0.076, z: 0.0 }, poly(0x17181a));
    s.box(0.026, 0.004, 0.006, { y: 0.092, z: 0.014 }, poly(0x17181a));
    s.box(0.018, 0.014, 0.001, { y: 0.078, z: 0.012 }, glow(0x2a4a5a, 0.5));
    s.box(0.0018, 0.0018, 0.001, { y: 0.0855, z: 0.011 }, glow(0xff3020, 3.5));
  }

  // ---- 弹匣（换弹时抽出） ----
  const magX = t >= 2 ? 0.024 : 0;
  const m = k.part('mag', new Vector3(0, -0.12, -0.02));
  m.box(0.022, 0.1, 0.034, { y: -0.13, z: -0.02, rx: -0.14 }, steel(0x30353a));
  m.rbox(0.03, 0.012 + magX * 0.4, 0.046, 0.003, { y: -0.135 - magX, z: -0.022, rx: -0.14 }, poly(0x141516));
  if (t >= 2) m.box(0.02, magX, 0.032, { y: -0.13 - magX, z: -0.021, rx: -0.14 }, steel(0x30353a));
  // 4 级：喇叭口弹匣井
  if (t >= 4) b.rbox(0.036, 0.014, 0.056, 0.004, { y: -0.13, z: -0.02, rx: -0.14 }, steel(0x6a7078));

  // 机瞄的瞄准点是准星点中心（和照门两点在同一高度）；5 级起换红点
  const sightY = t >= 5 ? 0.0855 : DOT_Y;
  return {
    gripR: new Vector3(0, -0.07, -0.014),
    gripL: new Vector3(0.026, -0.08, 0.008),
    muzzle: new Vector3(0, 0.046, L + (t >= 1 ? 0.034 : 0.012)),
    eject: new Vector3(-0.01, 0.07, 0.04),
    sight: new Vector3(0, sightY, -0.03),
    eyeRelief: 0.3,
    slideTravel: 0.03,
    action: 'semi',
  };
}
