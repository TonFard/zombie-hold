import { Vector3 } from 'three';
import { GunKit, brass, dark, glow, hole, outline, pin, poly, rail, side, steel, Z, type GunInfo } from './kit-ext';

/**
 * 铁幕轻机枪：方形机匣 + 供弹盖、侧挂弹药箱（能数清一发发子弹的弹链被拽进机匣）、
 * 带隔热罩的重枪管、提把、两脚架、固定枪托。
 */
export function lmg(k: GunKit): GunInfo {
  const { b, t } = k;
  const recv = dark(0x30343a);

  // ---- 机匣 ----
  side(
    b,
    outline([
      [-0.05, -0.02],
      [0.26, -0.02],
      [0.26, 0.07],
      [0.24, 0.08],
      [-0.04, 0.08],
      [-0.05, 0.07],
    ]),
    0.062,
    recv,
    0.005,
  );
  // 供弹盖（顶部，稍宽，带铰链）
  b.rbox(0.066, 0.016, 0.16, 0.004, { y: 0.078, z: 0.08 }, steel(0x40464d));
  b.tubeZ(0.005, 0.07, 10, { x: 0.0, y: 0.094, z: -0.02 }, steel(0x5a6066));
  rail(b, 0.0, 0.14, 0.104, dark(0x1c1e22), 0.024);
  // 拉机柄（右侧，可动）
  const bolt = k.part('bolt');
  bolt.box(0.02, 0.012, 0.012, { x: -0.04, y: 0.04, z: 0.18 }, steel(0x6a7076));
  bolt.cyl(0.008, 0.008, 0.012, 10, { x: -0.052, y: 0.046, z: 0.18, rz: Z }, poly(0x141516));
  b.box(0.002, 0.008, 0.14, { x: -0.0315, y: 0.04, z: 0.15 }, hole());
  // 抛壳口（下方）
  b.box(0.03, 0.002, 0.05, { y: -0.021, z: 0.06 }, hole());
  pin(b, 0.03, 0.0, 0.004, 0.0315, steel(0x6a7076));
  pin(b, 0.03, 0.24, 0.004, 0.0315, steel(0x6a7076));

  // ---- 握把 + 扳机护圈 ----
  side(
    b,
    outline(
      [
        [-0.03, -0.018],
        [0.1, -0.018],
        [0.1, -0.03],
        [0.09, -0.06, 0.07, -0.062],
        [0.03, -0.062],
        [0.018, -0.05],
        [-0.002, -0.15],
        [-0.044, -0.146],
        [-0.03, -0.04],
      ],
      [
        [
          [0.08, -0.03],
          [0.08, -0.05, 0.068, -0.052],
          [0.036, -0.052],
          [0.028, -0.03],
        ],
      ],
    ),
    0.038,
    poly(0x1e2022),
    0.003,
  );
  for (let i = 0; i < 5; i++) b.box(0.0015, 0.004, 0.03, { x: 0.0195, y: -0.065 - i * 0.017, z: -0.016 - i * 0.004, rx: -0.2 }, poly(0x0e0f10, { jitter: 0 }));
  b.box(0.006, 0.02, 0.005, { y: -0.05, z: 0.052, rx: 0.2 }, steel(0x8a8e92));

  // ---- 枪管：重枪管 + 带孔隔热罩 + 提把 + 消焰器 ----
  const bz = 0.26;
  b.tubeZ(0.014, 0.42, 18, { y: 0.038, z: bz }, dark(0x15171a));
  b.tubeZ(0.024, 0.26, 20, { y: 0.038, z: bz }, steel(0x40464d));
  for (let i = 0; i < 7; i++) for (const a of [0.4, -0.4, Math.PI / 2, Math.PI - 0.4, Math.PI + 0.4]) {
    b.cyl(0.004, 0.004, 0.002, 8, { x: Math.cos(a) * 0.0245, y: 0.038 + Math.sin(a) * 0.0245, z: bz + 0.02 + i * 0.034, rz: a - Z }, hole());
  }
  // 提把
  b.box(0.012, 0.03, 0.012, { y: 0.06, z: bz + 0.04 }, dark(0x22252a));
  b.rod([0.0, 0.09, bz + 0.0], [0.0, 0.09, bz + 0.12], 0.007, poly(0x1a1b1d), 10);
  b.rod([0.0, 0.065, bz + 0.0], [0.0, 0.09, bz + 0.0], 0.005, dark(0x22252a), 8);
  b.rod([0.0, 0.065, bz + 0.12], [0.0, 0.09, bz + 0.12], 0.005, dark(0x22252a), 8);
  // 消焰器（鸟笼式）
  const mz = bz + 0.42;
  b.lathe([[0, 0], [0.018, 0], [0.018, 0.06], [0, 0.06]], 16, { y: 0.038, z: mz }, dark(0x1c1e22));
  for (let i = 0; i < 5; i++) {
    const a = (i / 5) * Math.PI * 2;
    b.box(0.003, 0.003, 0.04, { x: Math.cos(a) * 0.0175, y: 0.038 + Math.sin(a) * 0.0175, z: mz + 0.035 }, hole());
  }
  // 机瞄：照门（供弹盖导轨后端）+ 准星塔（枪口前）。
  // 以前照门是实心块 + 贴上去的黑色"缺口"，准星顶只有 0.08，比瞄准线低一大截，开镜时只能看到照门背面。
  // 现在照门是两只"耳朵"中间留真缺口，准星柱一直立到瞄准线，准星点中心 = 瞄准线 = 屏幕中心（弹着点）。
  // 准星点橙色发光、2 级起绿色氚光；照门两点米白，三点连一线
  const SL = 0.118; // 瞄准线高度
  const fz = mz - 0.03; // 准星塔位置
  const sightCol = dark(0x101113, { jitter: 0 });
  const rearDot = t >= 2 ? glow(0x7dff8a, 2.4) : glow(0xf2f2e6, 1.1);
  const frontDot = t >= 2 ? glow(0x9dffa8, 3.2) : glow(0xff8a2a, 2.6);
  b.box(0.032, 0.01, 0.012, { y: 0.101, z: 0.0 }, dark(0x1a1c1f)); // 照门座
  if (t >= 8) {
    // 装了反射镜：照门折倒，免得挡住镜框下沿
    b.box(0.026, 0.004, 0.018, { y: 0.108, z: -0.004 }, sightCol);
  } else {
    // 两只耳朵各 6mm 宽，中间缺口 7mm（照门离眼近，耳朵做窄些免得在屏幕上挡掉一大片；缺口两边各留一条亮缝）
    for (const x of [0.0065, -0.0065]) {
      b.box(0.006, 0.018, 0.008, { x, y: 0.115, z: 0.0 }, sightCol);
      b.box(0.0022, 0.0022, 0.001, { x, y: SL, z: -0.0045 }, rearDot);
    }
  }
  // 准星塔：枪管上的箍 + 两片护翼 + 中间的准星柱（离眼远，屏幕上只有照门缺口的 1/3 宽）
  // 箍：以前底面在 0.062，这里只有裸枪管（顶 0.052），整个准星塔悬空。
  // 现在箍从枪管顶面下方（0.046，咬住枪管）一直立到护翼底面，护翼和准星柱都落在箍上（盒子原点在底面）
  const wingY = (SL - 0.002 + 0.07) / 2; // 护翼底面
  const postY = (SL + 0.005 + 0.07) / 2; // 准星柱原来的底面；柱顶不变
  const postTop = postY + SL + 0.005 - 0.07;
  b.box(0.031, wingY - 0.046, 0.016, { y: 0.046, z: fz }, dark(0x1a1c1f));
  for (const x of [0.014, -0.014]) b.box(0.003, SL - 0.072, 0.012, { x, y: wingY, z: fz }, dark(0x1a1c1f));
  // 准星离眼睛约 0.7m，点做大一些（屏幕上和照门点差不多大）
  b.box(0.009, postTop - wingY, 0.008, { y: wingY, z: fz }, sightCol);
  b.box(0.0076, 0.0076, 0.001, { y: SL, z: fz - 0.0045 }, frontDot);

  // ---- 两脚架（折叠在枪管下） ----
  b.box(0.026, 0.012, 0.02, { y: 0.008, z: bz + 0.28 }, dark(0x22252a));
  for (const x of [0.012, -0.012]) b.rod([x, 0.01, bz + 0.28], [x * 1.3, 0.004, bz + 0.1], 0.004, steel(0x5a6066), 8);

  // ---- 弹药箱 + 弹链（弹链会随射击被拽进去） ----
  const box = k.part('mag', new Vector3(0, -0.04, 0.1));
  box.rbox(0.07, 0.11, 0.1, 0.008, { x: 0.012, y: -0.15, z: 0.1 }, poly(0x3a4230));
  box.rbox(0.074, 0.012, 0.104, 0.004, { x: 0.012, y: -0.045, z: 0.1 }, poly(0x2a3022));
  box.box(0.04, 0.006, 0.01, { x: 0.012, y: -0.096, z: 0.152 }, steel(0x8a8e92)); // 提手
  box.box(0.001, 0.02, 0.05, { x: 0.0475, y: -0.12, z: 0.1 }, poly(t >= 6 ? 0xc89a3a : 0xd8d0b0, { jitter: 0.05 })); // 标签
  // 弹链：从弹药箱口到机匣的一串子弹
  const belt = k.part('belt');
  for (let i = 0; i < 6; i++) {
    const y = -0.045 + i * 0.011;
    const x = 0.03 - i * 0.004;
    belt.cyl(0.0042, 0.0042, 0.026, 8, { x, y, z: 0.1, rx: Z }, brass());
    belt.cone(0.0042, 0.008, 8, { x, y, z: 0.126, rx: Z }, t >= 7 ? dark(0x1a1c1f) : steel(0xb07a40));
    belt.box(0.012, 0.004, 0.006, { x, y: y - 0.004, z: 0.105 }, dark(0x22252a));
  }

  // ---- 固定枪托 ----
  side(
    b,
    outline([
      [-0.05, 0.07],
      [-0.05, -0.02],
      [-0.29, -0.08],
      [-0.32, -0.08],
      [-0.32, 0.06],
      [-0.12, 0.07],
    ]),
    0.042,
    poly(0x232528),
    0.006,
  );
  b.rbox(0.048, 0.15, 0.018, 0.005, { y: -0.082, z: -0.325 }, poly(0x0f1011));
  b.torus(0.008, 0.002, 6, 12, { y: -0.04, z: -0.2, ry: Z }, steel(0x8a8e92));

  // 2 级：两脚架展开得更稳（脚垫）；4 级：枪管加装散热片；5 级：压制射击发光条
  if (t >= 2) for (const x of [0.0156, -0.0156]) b.sphere(0.005, 8, 6, { x, y: 0.004, z: bz + 0.1 }, poly(0x111213));
  if (t >= 4) for (let i = 0; i < 5; i++) b.cyl(0.028, 0.028, 0.003, 18, { y: 0.038, z: bz + 0.27 + i * 0.02, rx: Z }, steel(0x6f777f));
  if (t >= 5) for (const x of [0.026, -0.026]) b.box(0.002, 0.003, 0.22, { x, y: 0.038, z: bz + 0.13 }, glow(0x6ad0ff, 2.0));
  // 8 级：反射式瞄具。以前是实心盒子，红点藏在盒子里面，开镜只看到盒子背面；
  // 现在是开放式镜框（底座 + 两根立柱 + 顶梁 + 前镜片框），中间全空，红点浮在镜框正中 = 屏幕中心。
  // 准星点在红点下方约 1/3 处（下三分之一共视），不会和红点抢位置
  let sightY = SL;
  if (t >= 8) {
    const RY = 0.13; // 红点高度
    const frame = poly(0x17181a);
    // 底座：z 0.04~0.09，落在供弹盖导轨（z 0~0.14，齿顶 0.104）上；以前底面在 0.106，悬空 2mm
    b.rbox(0.036, 0.01, 0.05, 0.003, { y: 0.104, z: 0.065 }, frame); // 底座顶面 0.114 不变
    // 立柱：以前从 0.132 起，和底座之间空着 1.8cm；现在往下接到底座顶面（顶端 0.176 不变）
    for (const x of [0.016, -0.016]) b.box(0.004, 0.176 - 0.114, 0.03, { x, y: 0.114, z: 0.07 }, frame);
    b.box(0.036, 0.004, 0.03, { y: 0.156, z: 0.07 }, frame); // 顶梁
    // 前镜片框（细边，镜片本身不画：不透明的镜片会挡住目标）
    const rim = dark(0x2a4a5a, { jitter: 0 });
    b.box(0.028, 0.002, 0.002, { y: 0.153, z: 0.086 }, rim);
    b.box(0.028, 0.002, 0.002, { y: 0.111, z: 0.086 }, rim);
    b.box(0.007, 0.004, 0.012, { x: 0.02, y: 0.14, z: 0.068 }, steel(0x5a6066)); // 亮度旋钮
    b.box(0.0024, 0.0024, 0.001, { y: RY, z: 0.085 }, glow(0xff3020, 3.5));
    sightY = RY;
  }

  return {
    gripR: new Vector3(0, -0.08, -0.022),
    gripL: new Vector3(0, 0.0, bz + 0.12),
    muzzle: new Vector3(0, 0.038, mz + 0.06),
    eject: new Vector3(0, -0.02, 0.06),
    sight: new Vector3(0, sightY, 0.0),
    eyeRelief: 0.22,
    slideTravel: 0.03,
    action: 'auto',
  };
}
