import { Vector3 } from 'three';
import { GunKit, dark, glow, hole, outline, pin, poly, rail, side, steel, Z, type GunInfo } from './kit-ext';

/** 蝰蛇冲锋枪：方形机匣、带散热孔的枪管护套、左侧拉机柄（开火时前后动）、直弹匣 / 弹鼓、折叠枪托 */
export function smg(k: GunKit): GunInfo {
  const { b, t } = k;
  const recv = dark(0x2e3238);
  const barrelLen = t >= 6 ? 0.13 : 0.07;

  // ---- 机匣 ----
  side(
    b,
    outline([
      [-0.03, -0.012],
      [0.23, -0.012],
      [0.23, 0.05],
      [0.215, 0.064],
      [-0.02, 0.064],
      [-0.03, 0.054],
    ]),
    0.044,
    recv,
    0.004,
  );
  // 下机匣 + 扳机护圈 + 握把，一体轮廓
  side(
    b,
    outline(
      [
        [-0.02, -0.01],
        [0.12, -0.01],
        [0.12, -0.022],
        [0.094, -0.022],
        [0.094, -0.05, 0.075, -0.052],
        [0.04, -0.052],
        [0.024, -0.04],
        [0.006, -0.135],
        [-0.036, -0.13],
        [-0.022, -0.03],
      ],
      [
        [
          [0.083, -0.022],
          [0.084, -0.042, 0.072, -0.043],
          [0.046, -0.043],
          [0.036, -0.022],
        ],
      ],
    ),
    0.036,
    poly(0x1d1f22),
    0.003,
  );
  for (let i = 0; i < 5; i++) b.box(0.0015, 0.004, 0.032, { x: 0.0185, y: -0.05 - i * 0.017, z: -0.012 - i * 0.004, rx: -0.2 }, poly(0x0e0f10, { jitter: 0 }));
  b.box(0.006, 0.02, 0.005, { y: -0.04, z: 0.06, rx: 0.2 }, steel(0x8a8e92)); // 扳机
  pin(b, 0.015, 0.03, 0.0035, 0.0225, steel(0x5a6066));
  pin(b, 0.015, 0.19, 0.0035, 0.0225, steel(0x5a6066));
  // 快慢机
  b.box(0.003, 0.008, 0.016, { x: 0.0225, y: -0.002, z: 0.0 }, steel(0x9a9ea2));
  b.box(0.0012, 0.003, 0.003, { x: 0.0236, y: 0.004, z: 0.012 }, glow(0xff4030, 1.4));
  // 抛壳口（右侧）+ 顶部导轨
  b.box(0.002, 0.016, 0.04, { x: -0.022, y: 0.026, z: 0.12 }, hole());
  rail(b, 0.0, 0.2, 0.072, dark(0x1a1c1f));
  // 拉机柄槽
  b.box(0.0015, 0.006, 0.12, { x: 0.0225, y: 0.038, z: 0.08 }, hole());

  // ---- 枪管护套 + 枪管 ----
  b.tubeZ(0.02, 0.18, 16, { y: 0.026, z: 0.23 }, steel(0x40464d));
  for (let i = 0; i < 6; i++) for (const a of [0.5, -0.5, 1.6]) b.box(0.002, 0.007, 0.014, { x: Math.cos(a) * 0.0205, y: 0.026 + Math.sin(a) * 0.0205 - 0.0035, z: 0.25 + i * 0.026, rz: a }, hole());
  b.tubeZ(0.009, barrelLen, 14, { y: 0.026, z: 0.41 }, dark(0x15171a));
  const muzzleZ = 0.41 + barrelLen;
  // 前握把（2 级起换带护手的）
  if (t >= 2) {
    b.rbox(0.03, 0.075, 0.032, 0.008, { y: -0.08, z: 0.31, rx: 0.08 }, poly(0x26282b));
    for (let i = 0; i < 4; i++) b.box(0.032, 0.003, 0.03, { y: -0.04 - i * 0.012, z: 0.31 }, poly(0x141516, { jitter: 0 }));
  } else {
    b.rbox(0.03, 0.06, 0.03, 0.008, { y: -0.065, z: 0.3 }, poly(0x26282b));
  }
  b.box(0.026, 0.018, 0.05, { y: -0.004, z: 0.3 }, dark(0x1a1c1f));
  // 机瞄（MP5 式）：照门是真正中空的觇孔环，准星是带护圈的细柱，瞄准时准星点落在两个圆环的圆心。
  // 以前照门是一整块实心方块正好挡在瞄准线上（只贴了块黑色假装是孔），准星又比瞄准线低，
  // 开镜只能看到一块黑。准星点中心 = 瞄准点 = 屏幕中心（弹着点）。
  // 准星点橙色发光，2 级起换氚光（绿色发光），亮背景和夜里都能看清
  const IRON_Y = 0.083;
  const sightCol = dark(0x101113, { jitter: 0 });
  // 准星座卡在护套上，护圈下沿正好压在座上
  b.box(0.008, 0.026, 0.012, { y: 0.046, z: 0.4 }, sightCol);
  b.box(0.0035, 0.011, 0.005, { y: 0.07, z: 0.4 }, sightCol);
  b.torus(0.0105, 0.0016, 6, 20, { y: IRON_Y, z: 0.4 }, sightCol);
  // 准星离眼睛约 0.6 米，点要做大一些屏幕上才有 8~9 像素；装反射式瞄具后不再发光，免得和红点抢
  const frontDot = t >= 8 ? sightCol : t >= 2 ? glow(0x9dffa8, 3.2) : glow(0xff8a2a, 2.6);
  b.box(0.0065, 0.0065, 0.001, { y: IRON_Y - 0.00325, z: 0.3965 }, frontDot);
  // 照门觇孔：8 级装反射式瞄具后拆掉
  if (t < 8) {
    b.box(0.024, 0.004, 0.014, { y: 0.07, z: 0.012 }, sightCol);
    b.torus(0.0085, 0.0025, 6, 20, { y: IRON_Y, z: 0.012 }, sightCol);
    for (const x of [0.0125, -0.0125]) b.box(0.003, 0.02, 0.01, { x, y: 0.072, z: 0.012 }, sightCol); // 护耳
  }

  // ---- 拉机柄（随枪机前后动） ----
  const bolt = k.part('bolt');
  bolt.box(0.016, 0.008, 0.008, { x: 0.03, y: 0.034, z: 0.1 }, steel(0x6a7076));
  bolt.cyl(0.006, 0.006, 0.01, 10, { x: 0.039, y: 0.038, z: 0.1, rz: Z }, poly(0x141516));

  // ---- 弹匣 / 弹鼓（可拆） ----
  const m = k.part('mag', new Vector3(0, -0.02, 0.14));
  if (t >= 2) {
    // 弹鼓：圆筒 + 透明窗口看到子弹
    m.cyl(0.062, 0.062, 0.046, 24, { x: -0.023, y: -0.09, z: 0.15, rz: Z }, steel(0x353b42));
    m.cyl(0.064, 0.064, 0.008, 24, { x: 0.022, y: -0.09, z: 0.15, rz: Z }, steel(0x5a6068));
    m.cyl(0.018, 0.018, 0.006, 12, { x: 0.03, y: -0.09, z: 0.15, rz: Z }, dark(0x15171a));
    m.box(0.004, 0.004, 0.022, { x: 0.034, y: -0.09, z: 0.15 }, steel(0x9a9ea2));
    for (let i = 0; i < 10; i++) {
      const a = (i / 10) * Math.PI * 2;
      m.box(0.002, 0.008, 0.004, { x: 0.026, y: -0.09 + Math.sin(a) * 0.045 - 0.004, z: 0.15 + Math.cos(a) * 0.045 }, hole());
    }
    m.box(0.026, 0.04, 0.03, { y: -0.045, z: 0.15 }, steel(0x353b42));
    if (t >= 7) m.cyl(0.062, 0.062, 0.03, 24, { x: -0.06, y: -0.09, z: 0.15, rz: Z }, steel(0x353b42)); // 双联弹鼓
  } else {
    m.box(0.026, 0.15, 0.036, { y: -0.16, z: 0.142, rx: 0.12 }, steel(0x30353a));
    for (let i = 0; i < 5; i++) m.box(0.0275, 0.004, 0.03, { y: -0.03 - i * 0.026, z: 0.146 - i * 0.003, rx: 0.12 }, steel(0x23272b));
    m.rbox(0.03, 0.012, 0.042, 0.003, { y: -0.172, z: 0.122, rx: 0.12 }, poly(0x141516));
    if (t >= 1) m.box(0.028, 0.012, 0.004, { y: -0.03, z: 0.165, rx: 0.12 }, poly(0xc03a2a, { jitter: 0.05 }));
  }

  // ---- 枪托：钢丝折叠托，3 级换实心伸缩托 ----
  if (t >= 3) {
    side(
      b,
      outline([
        [-0.03, 0.05],
        [-0.03, -0.02],
        [-0.22, -0.05],
        [-0.25, -0.05],
        [-0.25, 0.05],
      ], [[
        [-0.08, 0.03],
        [-0.08, -0.01],
        [-0.19, -0.03],
        [-0.19, 0.03],
      ]]),
      0.03,
      poly(0x232528),
      0.004,
    );
    b.rbox(0.036, 0.11, 0.018, 0.005, { y: -0.058, z: -0.255 }, poly(0x101112));
  } else {
    for (const x of [0.014, -0.014]) b.rod([x, 0.03, -0.03], [x, 0.0, -0.25], 0.004, dark(), 8);
    b.rod([0.014, -0.004, -0.25], [-0.014, -0.004, -0.25], 0.004, dark(), 8);
    b.rbox(0.034, 0.07, 0.01, 0.003, { y: -0.04, z: -0.255 }, dark(0x1f2226));
  }
  // 4 级：补偿器
  if (t >= 4) {
    b.tubeZ(0.014, 0.04, 14, { y: 0.026, z: muzzleZ }, dark(0x1c1e22));
    for (let i = 0; i < 3; i++) b.box(0.018, 0.003, 0.006, { y: 0.039, z: muzzleZ + 0.008 + i * 0.011 }, hole());
  }
  // 5 级：散热片 + 发光热管
  if (t >= 5) {
    for (let i = 0; i < 7; i++) b.cyl(0.026, 0.026, 0.003, 16, { y: 0.026, z: 0.25 + i * 0.022, rx: Z }, steel(0x6f777f));
    for (const x of [0.024, -0.024]) b.box(0.003, 0.003, 0.17, { x, y: 0.026, z: 0.32 }, glow(0xff8a2a, 2.2));
  }
  // 8 级：反射式瞄具。以前是一整块实心圆角盒，红点埋在盒子里面，开镜只看到盒子屁股；
  // 现在是中空的框（没有不透明镜片），红点悬在窗口中间，比准星护圈高一截（下 1/3 共线）
  const DOT_Y = 0.102;
  if (t >= 8) {
    const housing = poly(0x17181a);
    b.rbox(0.03, 0.006, 0.05, 0.002, { y: 0.072, z: 0.045 }, housing);
    for (const x of [0.0145, -0.0145]) b.box(0.003, 0.04, 0.04, { x, y: 0.078, z: 0.05 }, housing);
    b.box(0.032, 0.003, 0.04, { y: 0.118, z: 0.05 }, housing);
    b.box(0.006, 0.008, 0.012, { x: 0.018, y: 0.1, z: 0.04 }, dark(0x2a2d31)); // 亮度旋钮
    // 前镜框内沿一圈淡青色，看起来像镀膜玻璃的边
    const lens = glow(0x3a7a8a, 0.6);
    b.box(0.026, 0.0008, 0.001, { y: 0.117, z: 0.0695 }, lens);
    b.box(0.026, 0.0008, 0.001, { y: 0.078, z: 0.0695 }, lens);
    for (const x of [0.0128, -0.0128]) b.box(0.0008, 0.039, 0.001, { x, y: 0.0785, z: 0.0695 }, lens);
    b.box(0.0038, 0.0038, 0.001, { y: DOT_Y - 0.0019, z: 0.06 }, glow(0xff3020, 4.5));
  }

  return {
    gripR: new Vector3(0, -0.07, -0.014),
    gripL: new Vector3(0, -0.07, 0.31),
    muzzle: new Vector3(0, 0.026, muzzleZ + (t >= 4 ? 0.04 : 0)),
    eject: new Vector3(-0.024, 0.03, 0.12),
    // 瞄准点：机瞄是准星点中心（照门觇孔同心）；8 级起是反射式瞄具的红点
    sight: t >= 8 ? new Vector3(0, DOT_Y, 0.06) : new Vector3(0, IRON_Y, 0.012),
    eyeRelief: 0.2,
    slideTravel: 0.03,
    action: 'auto',
  };
}
