import { Vector3 } from 'three';
import { GunKit, brass, dark, glow, hole, outline, pin, poly, rail, side, steel, wood, Z, type GunInfo } from './kit-ext';

/** 铁砧霰弹枪：木质枪托和握把、机匣、长枪管 + 管状弹仓、泵动护木（开火后前后拉）、通风肋 + 珠状准星 */
export function shotgun(k: GunKit): GunInfo {
  const { b, t } = k;
  const tube = 0.42 + (t >= 2 ? 0.1 : 0);
  const stockCol = 0x6a4a2c;

  // ---- 枪托（带握把的一体木托） ----
  side(
    b,
    outline([
      [-0.03, 0.03],
      [-0.03, -0.01],
      [-0.012, -0.03],
      [-0.03, -0.1],
      [-0.06, -0.1],
      [-0.07, -0.05],
      [-0.36, -0.1],
      [-0.37, -0.1],
      [-0.37, 0.02],
      [-0.2, 0.028, -0.07, 0.03],
    ]),
    0.04,
    wood(stockCol),
    0.006,
  );
  // 托底板、背带环、握把方格纹
  b.rbox(0.044, 0.13, 0.016, 0.004, { y: -0.103, z: -0.375, rx: 0.02 }, poly(0x141414));
  b.torus(0.008, 0.002, 6, 12, { y: -0.08, z: -0.3, ry: Z }, steel(0x8a8e92));
  for (let i = 0; i < 4; i++) for (let j = 0; j < 3; j++) b.box(0.0015, 0.005, 0.005, { x: 0.0205, y: -0.035 - i * 0.012, z: -0.03 - j * 0.009 + i * 0.004 }, wood(0x2c1e12, { jitter: 0 }));

  // ---- 机匣（扳机护圈一体） ----
  side(
    b,
    outline(
      [
        [-0.03, -0.012],
        [0.2, -0.012],
        [0.2, 0.05],
        [-0.03, 0.05],
      ],
      [],
    ),
    0.046,
    dark(0x2c3035),
    0.004,
  );
  b.torus(0.022, 0.004, 8, 16, { y: -0.012, z: 0.05, ry: Z, rz: Math.PI }, dark(0x22252a), Math.PI);
  b.box(0.006, 0.022, 0.005, { y: -0.03, z: 0.05, rx: 0.2 }, steel(0x8a8e92));
  b.box(0.004, 0.008, 0.02, { y: 0.052, z: -0.01 }, steel(0x8a8e92)); // 顶部保险
  pin(b, 0.0, 0.03, 0.003, 0.0235, steel(0x7a7e82));
  pin(b, 0.0, 0.16, 0.003, 0.0235, steel(0x7a7e82));
  // 抛壳口：能看到一枚红色霰弹
  b.box(0.002, 0.024, 0.07, { x: -0.0235, y: 0.012, z: 0.1 }, hole());
  b.cyl(0.0095, 0.0095, 0.04, 12, { x: -0.014, y: 0.024, z: 0.09, rx: Z }, poly(0xb8341e));
  // 装弹口（底部）
  b.box(0.026, 0.002, 0.07, { y: -0.0125, z: 0.13 }, hole());

  // ---- 枪管 + 通风肋 ----
  // 瞄准线：眼睛、（7 级的鬼环中心、）准星珠中心都在 SIGHT_Y 这条水平线上，准星珠中心就是弹着点（= 屏幕中心）。
  // 以前准星珠只有 3mm 而且不发光，瞄准点又放在机匣前端，眼睛贴着机匣，机匣顶面挡住大半画面、珠子根本找不到；
  // 现在通风肋垫高、瞄准线抬到机匣顶上 1.8cm，机匣和肋只在画面下方，肋一路"指"向发光的准星珠
  const SIGHT_Y = 0.068;
  const RIB_TOP = 0.058;
  b.tubeZ(0.0145, 0.56, 18, { y: 0.034, z: 0.2 }, dark(0x1f2226));
  b.box(0.01, 0.006, 0.54, { y: RIB_TOP - 0.003, z: 0.47 }, steel(0x464c53));
  for (let i = 0; i < 18; i++) b.box(0.006, 0.005, 0.006, { y: 0.0505, z: 0.215 + i * 0.03 }, dark(0x1a1c1f));
  // 中珠：肋中段一颗小白珠，瞄准时叠在准星珠正下方（"8"字），帮眼睛对齐枪管
  b.sphere(0.003, 8, 6, { y: RIB_TOP + 0.003, z: 0.46 }, glow(0xf2f2e6, 1.0));
  // 准星：黑色底座托着发光光纤珠；6 级起换绿色氚光。底座是暗色，亮背景前也能把珠子衬出来
  b.box(0.006, SIGHT_Y - RIB_TOP - 0.002, 0.012, { y: (SIGHT_Y + RIB_TOP - 0.002) / 2, z: 0.743 }, dark(0x101113, { jitter: 0 }));
  b.sphere(0.0048, 10, 8, { y: SIGHT_Y, z: 0.745 }, t >= 6 ? glow(0x9dffa8, 3.2) : glow(0xff8a2a, 2.6));
  // 扼流管（1 级加粗，6 级收束）
  const chokeR = t >= 6 ? 0.017 : t >= 1 ? 0.0175 : 0.0155;
  b.tubeZ(chokeR, 0.03, 18, { y: 0.034, z: 0.75 }, dark(0x15171a));
  b.cyl(0.0115, 0.0115, 0.002, 14, { y: 0.034, z: 0.781, rx: Z }, hole());
  // 管状弹仓 + 弹仓帽 + 枪管箍
  b.tubeZ(0.0125, tube, 16, { y: -0.006, z: 0.2 }, steel(0x353a40));
  b.tubeZ(0.0145, 0.02, 16, { y: -0.006, z: 0.2 + tube }, steel(0x6a7078));
  b.box(0.012, 0.03, 0.012, { y: -0.006, z: 0.2 + tube - 0.02 }, steel(0x6a7078));
  // 2 级：弹仓上能看到红色弹壳的观察窗
  if (t >= 2) for (let i = 0; i < 5; i++) b.box(0.002, 0.008, 0.016, { x: 0.0125, y: -0.01, z: 0.24 + i * 0.022 }, poly(0xb8341e));

  // ---- 泵动护木（可动） ----
  const pump = k.part('pump');
  pump.rbox(0.042, 0.042, 0.17, 0.014, { y: -0.026, z: 0.37 }, wood(0x7a5632));
  for (let i = 0; i < 9; i++) pump.box(0.044, 0.003, 0.004, { y: -0.012, z: 0.3 + i * 0.016 }, wood(0x2a1c10, { jitter: 0 }));
  pump.box(0.01, 0.005, 0.12, { x: 0.016, y: 0.004, z: 0.27 }, steel(0x4a5056)); // 连杆

  // 3 级：枪管散热罩
  if (t >= 3) {
    b.rbox(0.036, 0.022, 0.32, 0.008, { y: 0.034, z: 0.4 }, steel(0x50565d));
    for (let i = 0; i < 8; i++) for (const x of [0.018, -0.018]) b.rbox(0.002, 0.012, 0.022, 0.001, { x, y: 0.04, z: 0.26 + i * 0.038 }, hole());
  }
  // 4 级：侧挂弹袋（4 发）
  if (t >= 4) {
    b.rbox(0.008, 0.04, 0.11, 0.003, { x: 0.026, y: 0.004, z: 0.09 }, poly(0x2c2a24));
    for (let i = 0; i < 4; i++) {
      b.cyl(0.0095, 0.0095, 0.034, 12, { x: 0.036, y: 0.0, z: 0.05 + i * 0.026 }, poly(0xb8341e, { jitter: 0.1 }));
      b.cyl(0.0098, 0.0098, 0.009, 12, { x: 0.036, y: -0.003, z: 0.05 + i * 0.026 }, brass());
    }
  }
  // 5 级：龙息弹，枪口和枪管发光
  if (t >= 5) {
    b.lathe([[0.0, 0], [0.019, 0], [0.024, 0.02], [0.02, 0.04], [0.0, 0.04]], 18, { y: 0.034, z: 0.77 }, dark(0x1a1c20));
    b.cyl(0.0125, 0.0125, 0.002, 14, { y: 0.034, z: 0.811, rx: Z }, glow(0xff5a1a, 2.6));
    for (const x of [0.0146, -0.0146]) b.box(0.002, 0.003, 0.36, { x, y: 0.036, z: 0.4 }, glow(0xff7a2a, 2.0));
  }
  // 7 级：顶部导轨 + 鬼环照门
  if (t >= 7) {
    // 鬼环中心和准星珠同高，开镜时珠子正好落在环中心；两侧护耳在环外，不挡视线
    rail(b, 0.0, 0.16, 0.058, dark(0x1a1c1f));
    b.box(0.014, 0.005, 0.01, { y: 0.0585, z: 0.03 }, dark(0x1a1c1f));
    b.torus(0.0085, 0.0018, 8, 20, { y: SIGHT_Y, z: 0.03 }, dark(0x1a1c1f));
    for (const x of [0.0125, -0.0125]) b.box(0.003, 0.018, 0.008, { x, y: 0.065, z: 0.03 }, dark(0x1a1c1f));
  }

  return {
    gripR: new Vector3(0, -0.07, -0.03),
    gripL: new Vector3(0, -0.03, 0.37),
    muzzle: new Vector3(0, 0.034, t >= 5 ? 0.81 : 0.78),
    eject: new Vector3(-0.024, 0.02, 0.1),
    sight: new Vector3(0, SIGHT_Y, 0.03), // 瞄准点在机匣后部，眼睛在枪托上方，整条肋和准星珠都露出来
    eyeRelief: 0.2,
    slideTravel: 0.08,
    // 全自动（AA-12 式）：没有泵动，开火只有枪机后坐
    action: 'auto',
  };
}
