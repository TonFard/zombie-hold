import { Vector3 } from 'three';
import { GunKit, brass, dark, glow, hole, outline, pin, poly, side, steel, Z, type GunInfo } from './kit-ext';

/**
 * 寒鸦狙击步枪（栓动）：铝合金底盘、带凹槽的长枪管、出气孔制退器、栓动手柄（开火后拉栓）、
 * 带旋钮的大倍率瞄准镜（镜片反光）、可调贴腮板、折叠两脚架。
 */
export function sniper(k: GunKit): GunInfo {
  const { b, t } = k;
  const chassis = poly(t >= 6 ? 0x4a4f3a : 0x2b2e30);
  const metalDark = dark(0x24272b);

  // ---- 底盘：握把 + 扳机护圈 + 前托，一体轮廓 ----
  side(
    b,
    outline(
      [
        [-0.06, 0.03],
        [0.4, 0.03],
        [0.4, -0.02],
        [0.38, -0.03],
        [0.17, -0.03],
        [0.15, -0.04],
        [0.1, -0.04],
        [0.085, -0.03],
        [0.08, -0.05, 0.065, -0.055],
        [0.03, -0.055],
        [0.018, -0.044],
        [-0.004, -0.145],
        [-0.046, -0.14],
        [-0.034, -0.03],
        [-0.06, -0.02],
      ],
      [
        [
          [0.07, -0.03],
          [0.07, -0.046, 0.06, -0.047],
          [0.036, -0.047],
          [0.028, -0.03],
        ],
      ],
    ),
    0.05,
    chassis,
    0.005,
  );
  // 前托减重孔
  for (let i = 0; i < 4; i++) for (const x of [0.0252, -0.0252]) b.rbox(0.002, 0.016, 0.04, 0.003, { x, y: -0.018, z: 0.2 + i * 0.05 }, hole());
  for (let i = 0; i < 5; i++) b.box(0.0015, 0.004, 0.032, { x: 0.0255, y: -0.06 - i * 0.016, z: -0.02 - i * 0.004, rx: -0.2 }, poly(0x0e0f10, { jitter: 0 }));
  b.box(0.006, 0.02, 0.005, { y: -0.045, z: 0.048, rx: 0.2 }, steel(0x9a9ea2));
  pin(b, 0.0, 0.0, 0.004, 0.0255, steel(0x6a7076));
  pin(b, 0.0, 0.14, 0.004, 0.0255, steel(0x6a7076));

  // ---- 机匣（圆柱）+ 抛壳口 ----
  b.tubeZ(0.02, 0.2, 20, { y: 0.046, z: -0.04 }, steel(0x3a4047));
  b.box(0.002, 0.018, 0.06, { x: -0.0195, y: 0.042, z: 0.06 }, hole());
  b.cyl(0.006, 0.006, 0.03, 12, { x: -0.012, y: 0.046, z: 0.06, rx: Z }, brass());
  // ---- 枪管：带凹槽的重枪管 ----
  b.tubeZ(0.015, 0.5, 20, { y: 0.046, z: 0.16 }, metalDark);
  for (let i = 0; i < 6; i++) {
    const a = (i / 6) * Math.PI * 2;
    b.box(0.003, 0.003, 0.3, { x: Math.cos(a) * 0.014, y: 0.046 + Math.sin(a) * 0.014 - 0.0015, z: 0.48, rz: a }, dark(0x121315));
  }
  // 制退器：三室
  const bz = 0.66;
  b.lathe([[0, 0], [0.019, 0], [0.019, 0.07], [0, 0.07]], 18, { y: 0.046, z: bz }, dark(0x1a1c20));
  for (let i = 0; i < 3; i++) for (const x of [0.0185, -0.0185]) b.box(0.002, 0.014, 0.012, { x, y: 0.039, z: bz + 0.012 + i * 0.02 }, hole());
  b.cyl(0.007, 0.007, 0.002, 12, { y: 0.046, z: bz + 0.071, rx: Z }, hole());
  // 8 级：消音器
  const muzzleZ = t >= 8 ? bz + 0.2 : bz + 0.07;
  if (t >= 8) {
    b.lathe([[0, 0], [0.024, 0.004], [0.026, 0.02], [0.026, 0.19], [0.022, 0.2], [0, 0.2]], 22, { y: 0.046, z: bz }, poly(0x3c3a32));
  }

  // ---- 枪栓（可动：开火后拉栓、推栓） ----
  const bolt = k.part('bolt', new Vector3(0, 0.046, 0.02));
  bolt.tubeZ(0.012, 0.11, 14, { y: 0.046, z: -0.06 }, steel(0x8a9096));
  bolt.rod([0.0, 0.046, 0.03], [0.05, 0.03, 0.02], 0.004, steel(0x8a9096), 10);
  bolt.sphere(0.011, 12, 10, { x: 0.054, y: 0.028, z: 0.018 }, poly(0x15161a));

  // ---- 弹匣（短弹匣，5 发；2 级加长） ----
  const magH = t >= 2 ? 0.07 : 0.05;
  const m = k.part('mag', new Vector3(0, -0.04, 0.125));
  m.box(0.03, magH, 0.06, { y: -0.03 - magH, z: 0.125 }, steel(0x2b2f34));
  m.rbox(0.034, 0.01, 0.064, 0.003, { y: -0.04 - magH, z: 0.125 }, poly(0x111213));

  // ---- 枪托：骨架托 + 贴腮板 + 单脚架 ----
  side(
    b,
    outline(
      [
        [-0.06, 0.03],
        [-0.06, -0.03],
        [-0.3, -0.08],
        [-0.34, -0.08],
        [-0.34, 0.07],
        [-0.12, 0.07],
        [-0.1, 0.03],
      ],
      [
        [
          [-0.12, 0.01],
          [-0.12, -0.02],
          [-0.27, -0.055],
          [-0.27, 0.01],
        ],
      ],
    ),
    0.036,
    chassis,
    0.005,
  );
  b.rbox(0.042, 0.016, 0.14, 0.006, { y: 0.07, z: -0.24 }, poly(0x1a1b1d)); // 贴腮板
  for (const z of [-0.2, -0.28]) b.cyl(0.004, 0.004, 0.02, 8, { y: 0.054, z }, steel(0x8a8e92));
  b.rbox(0.046, 0.16, 0.018, 0.005, { y: -0.085, z: -0.345 }, poly(0x0f1011));
  b.box(0.012, 0.05, 0.012, { y: -0.13, z: -0.28 }, dark()); // 单脚架

  // ---- 瞄准镜：车削出物镜 / 目镜，带调节旋钮和镜座 ----
  const sy = 0.112;
  b.lathe(
    [
      [0, -0.11],
      [0.022, -0.11],
      [0.024, -0.09],
      [0.017, -0.06],
      [0.017, 0.1],
      [0.03, 0.15],
      [0.03, 0.19],
      [0, 0.19],
    ],
    28,
    { y: sy, z: 0.04 },
    dark(0x141618),
  );
  b.cyl(0.011, 0.011, 0.016, 16, { y: sy + 0.016, z: 0.06 }, dark(0x1e2124)); // 高低旋钮
  b.cyl(0.011, 0.011, 0.016, 16, { x: 0.016, y: sy, z: 0.06, rz: -Z }, dark(0x1e2124)); // 风偏旋钮
  for (let i = 0; i < 8; i++) {
    const a = (i / 8) * Math.PI * 2;
    b.box(0.002, 0.016, 0.003, { x: Math.cos(a) * 0.011, y: sy + 0.016, z: 0.06 + Math.sin(a) * 0.011, ry: -a }, steel(0x6a7076));
  }
  b.cyl(0.006, 0.006, 0.014, 12, { x: -0.018, y: sy, z: 0.02, rz: Z }, dark(0x1e2124)); // 视差旋钮
  for (const z of [-0.01, 0.12]) {
    // 镜座：底座夹在导轨上，立柱一直顶到镜环（镜筒下沿 sy - 0.019）
    b.box(0.03, 0.014, 0.018, { y: 0.066, z }, dark(0x1a1c1f));
    b.box(0.014, sy - 0.019 - 0.07, 0.014, { y: (0.07 + sy - 0.019) / 2, z }, dark(0x1a1c1f));
    b.box(0.02, 0.006, 0.016, { y: sy - 0.02, z }, dark(0x1a1c1f));
    b.torus(0.019, 0.004, 8, 20, { y: sy, z }, dark(0x1a1c1f));
  }
  b.cyl(0.028, 0.028, 0.001, 24, { y: sy, z: 0.231, rx: Z }, glow(0x3a6aff, 1.6));
  // 目镜：原来是一片几乎全黑的镜片，举镜过程中（界面层镜框遮罩出现前）镜筒堵在屏幕中间，看不到瞄点。
  // 改成微亮的镜片 + 黑色十字分划 + 发光红点。viewmodel 举镜时会把镜筒再压低 0.012（缩放 0.95），
  // 视线正中打在镜片上沿 sy + 0.012 / 0.95 处，所以分划中心放在那里，举满时红点正好在屏幕中心
  const ey = sy + 0.012 / 0.95;
  b.cyl(0.02, 0.02, 0.001, 24, { y: sy, z: -0.071, rx: Z }, glow(0x1c3444, 0.7));
  const reticle = poly(0x050505, { jitter: 0 });
  const half = Math.sqrt(0.02 * 0.02 - (ey - sy) * (ey - sy)); // 横线在镜片圆内的半长
  b.box(half * 2, 0.0005, 0.001, { y: ey, z: -0.0717 }, reticle);
  b.box(0.0005, 0.04, 0.001, { y: sy, z: -0.0717 }, reticle);
  b.cyl(0.0011, 0.0011, 0.001, 10, { y: ey, z: -0.0724, rx: Z }, glow(0xff3020, 3.5));
  // 3 级：镜头遮光罩
  if (t >= 3) b.tubeZ(0.031, 0.04, 24, { y: sy, z: 0.23 }, dark(0x141618));

  // ---- 两脚架（折叠在前托下） ----
  const fold = t >= 1 ? 1 : 0;
  b.box(0.03, 0.012, 0.03, { y: -0.04, z: 0.36 }, dark(0x22252a));
  for (const x of [0.014, -0.014]) b.rod([x, -0.036, 0.36], [x * (1 + fold * 0.3), -0.04, 0.53], 0.0045, steel(0x5a6066), 8);
  for (const x of [0.014, -0.014]) b.sphere(0.006, 8, 6, { x: x * (1 + fold * 0.3), y: -0.04, z: 0.535 }, poly(0x111213));

  // 5 级：镜上的激光测距仪
  if (t >= 5) {
    b.rbox(0.024, 0.02, 0.06, 0.004, { x: 0.03, y: sy + 0.004, z: 0.16 }, poly(0x17181a));
    b.cyl(0.005, 0.005, 0.001, 10, { x: 0.03, y: sy + 0.014, z: 0.191, rx: Z }, glow(0xff2a1a, 3));
  }

  return {
    gripR: new Vector3(0, -0.08, -0.024),
    gripL: new Vector3(0, -0.02, 0.32),
    muzzle: new Vector3(0, 0.046, muzzleZ),
    eject: new Vector3(-0.022, 0.046, 0.06),
    sight: new Vector3(0, sy, -0.07),
    eyeRelief: 0.08,
    slideTravel: 0.08,
    action: 'bolt',
  };
}
