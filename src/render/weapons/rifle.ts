import { Vector3 } from 'three';
import { GunKit, dark, glow, hole, outline, pin, poly, rail, side, steel, Z, type GunInfo } from './kit-ext';

/**
 * 铁壁突击步枪（AR 式）：上下机匣、带 M-LOK 槽的长护木、全长导轨、提把式照门 / 翻转照门、
 * 拉机柄（开火时动）、带肋弹匣、可调枪托；4 级反射式瞄具、5 级 4 倍镜。
 */
export function rifle(k: GunKit): GunInfo {
  const { b, t } = k;
  const recv = dark(0x2a2e33);
  const lower = steel(0x353a41);

  // ---- 上机匣 ----
  side(
    b,
    outline([
      [-0.04, 0.0],
      [0.19, 0.0],
      [0.19, 0.056],
      [-0.04, 0.056],
    ]),
    0.044,
    recv,
    0.004,
  );
  rail(b, -0.04, 0.23, 0.066, dark(0x1c1e22));
  b.box(0.002, 0.018, 0.05, { x: -0.0225, y: 0.018, z: 0.12 }, hole()); // 抛壳口
  b.box(0.0025, 0.02, 0.054, { x: -0.0232, y: 0.017, z: 0.12 }, steel(0x484e55)); // 防尘盖
  b.cyl(0.006, 0.006, 0.012, 10, { x: -0.028, y: 0.03, z: 0.05, rz: Z }, steel(0x484e55)); // 助推器
  // ---- 下机匣 + 弹匣井 + 扳机护圈 + 握把 ----
  side(
    b,
    outline(
      [
        [-0.03, 0.002],
        [0.18, 0.002],
        [0.18, -0.03],
        [0.155, -0.034],
        [0.15, -0.07],
        [0.105, -0.07],
        [0.1, -0.034],
        [0.09, -0.034],
        [0.09, -0.05, 0.075, -0.052],
        [0.032, -0.052],
        [0.02, -0.04],
        [0.0, -0.14],
        [-0.04, -0.136],
        [-0.024, -0.03],
        [-0.03, -0.02],
      ],
      [
        [
          [0.08, -0.03],
          [0.08, -0.044, 0.07, -0.045],
          [0.04, -0.045],
          [0.032, -0.03],
        ],
      ],
    ),
    0.04,
    lower,
    0.003,
  );
  for (let i = 0; i < 5; i++) b.box(0.0015, 0.004, 0.03, { x: 0.0205, y: -0.055 - i * 0.017, z: -0.016 - i * 0.004, rx: -0.2 }, poly(0x0e0f10, { jitter: 0 }));
  b.box(0.006, 0.02, 0.005, { y: -0.044, z: 0.054, rx: 0.2 }, steel(0x8a8e92));
  b.box(0.003, 0.006, 0.016, { x: 0.0205, y: -0.012, z: 0.012 }, steel(0x9a9ea2)); // 快慢机
  b.box(0.003, 0.01, 0.01, { x: 0.0205, y: -0.025, z: 0.098 }, steel(0x6a7076)); // 弹匣释放钮
  b.box(0.003, 0.014, 0.02, { x: 0.0205, y: -0.004, z: 0.13 }, steel(0x6a7076)); // 空仓挂机
  pin(b, -0.008, 0.0, 0.003, 0.0205, steel(0x6a7076));
  pin(b, -0.008, 0.16, 0.003, 0.0205, steel(0x6a7076));

  // ---- 护木（八角形截面，带 M-LOK 槽）----
  const hgLen = t >= 6 ? 0.32 : 0.28;
  b.rbox(0.052, 0.054, hgLen, 0.012, { y: 0.0, z: 0.19 + hgLen / 2 }, poly(0x26282b));
  rail(b, 0.19, hgLen, 0.066, dark(0x1c1e22));
  for (let i = 0; i < Math.floor(hgLen / 0.04); i++) {
    for (const x of [0.0262, -0.0262]) b.rbox(0.002, 0.008, 0.024, 0.001, { x, y: 0.02, z: 0.21 + i * 0.04 }, hole());
    b.rbox(0.03, 0.002, 0.024, 0.001, { y: -0.001, z: 0.21 + i * 0.04 }, hole());
  }
  // ---- 枪管 + 准星座 + 消焰器 ----
  const bEnd = 0.19 + hgLen + 0.12;
  b.tubeZ(0.0105, bEnd - 0.19 - hgLen, 14, { y: 0.028, z: 0.19 + hgLen }, dark(0x15171a));
  b.box(0.012, 0.03, 0.014, { y: 0.028, z: 0.19 + hgLen + 0.03 }, steel(0x40464d));
  // 2 级：导气管露在外面
  if (t >= 2) b.tubeZ(0.004, hgLen + 0.03, 10, { y: 0.05, z: 0.19 }, steel(0x6a7076));
  const brake = t >= 3;
  if (brake) {
    b.lathe([[0.0, 0], [0.018, 0], [0.018, 0.06], [0.0, 0.06]], 16, { y: 0.028, z: bEnd }, dark(0x1c1e22));
    for (let i = 0; i < 4; i++) for (const x of [0.0175, -0.0175]) b.box(0.002, 0.01, 0.006, { x, y: 0.023, z: bEnd + 0.01 + i * 0.012 }, hole());
  } else {
    b.lathe([[0.0, 0], [0.014, 0], [0.014, 0.045], [0.0, 0.045]], 14, { y: 0.028, z: bEnd }, dark(0x1c1e22));
    for (let i = 0; i < 4; i++) {
      const a = (i / 4) * Math.PI * 2 + 0.4;
      b.box(0.002, 0.002, 0.03, { x: Math.cos(a) * 0.0135, y: 0.028 + Math.sin(a) * 0.0135, z: bEnd + 0.03 }, hole());
    }
  }
  const muzzleZ = bEnd + (brake ? 0.06 : 0.045);
  b.cyl(0.006, 0.006, 0.002, 12, { y: 0.028, z: muzzleZ + 0.001, rx: Z }, hole());

  // ---- 拉机柄（可动，开火时后坐） ----
  const ch = k.part('bolt');
  ch.box(0.03, 0.008, 0.016, { y: 0.056, z: -0.044 }, steel(0x40464d));
  ch.box(0.044, 0.006, 0.008, { y: 0.058, z: -0.05 }, steel(0x40464d));

  // ---- 弹匣（带肋，4 级加长） ----
  const magH = t >= 4 ? 0.19 : 0.15;
  const m = k.part('mag', new Vector3(0, -0.06, 0.13));
  m.push({ y: -0.065, z: 0.128, rx: 0.18 });
  m.box(0.026, magH, 0.05, { y: -magH }, steel(t >= 3 ? 0x16171a : 0x2f343a));
  for (const x of [0.0132, -0.0132]) for (let i = 0; i < 3; i++) m.box(0.001, magH * 0.85, 0.003, { x, y: -magH * 0.92, z: -0.016 + i * 0.016 }, steel(0x23272b));
  m.rbox(0.03, 0.012, 0.054, 0.003, { y: -magH - 0.01 }, poly(0x111213));
  m.pop();

  // ---- 枪托：伸缩托，带贴腮和缓冲管 ----
  b.tubeZ(0.014, 0.16, 14, { y: 0.02, z: -0.2 }, dark(0x1f2226));
  side(
    b,
    outline([
      [-0.13, 0.04],
      [-0.13, -0.005],
      [-0.27, -0.065],
      [-0.31, -0.07],
      [-0.31, 0.05],
      [-0.2, 0.05],
    ]),
    0.036,
    poly(0x232528),
    0.005,
  );
  b.rbox(0.042, 0.13, 0.016, 0.004, { y: -0.073, z: -0.315 }, poly(0x0f1011));
  for (let i = 0; i < 6; i++) b.box(0.016, 0.003, 0.006, { y: -0.01, z: -0.22 + i * 0.012 }, hole()); // 调节孔

  // ---- 瞄具：机械（觇孔照门 + 准星柱）/ 4 级反射式 / 5 级 4 倍镜 ----
  // 瞄准点（弹着点 = 屏幕中心）统一在 AIM 高度；导轨齿顶 0.066（齿底 0.062），瞄具都架在导轨上（盒子原点在底面）
  const AIM = 0.088;
  const frontZ = 0.19 + hgLen - 0.02;
  const sightCol = dark(0x101113, { jitter: 0 });
  let sightY = AIM;
  let sightZ = -0.01;
  let relief = 0.2;
  if (t >= 5) {
    // 4 倍镜：镜筒（车削轮廓）+ 镜座 + 调节旋钮 + 镜片反光
    b.lathe(
      [
        [0.0, -0.05],
        [0.02, -0.05],
        [0.02, -0.035],
        [0.014, -0.02],
        [0.014, 0.06],
        [0.024, 0.085],
        [0.024, 0.11],
        [0.0, 0.11],
      ],
      24,
      { y: 0.106, z: 0.04 },
      dark(0x16181a),
    );
    b.cyl(0.008, 0.008, 0.012, 14, { y: 0.12, z: 0.06 }, dark(0x22252a));
    b.cyl(0.008, 0.008, 0.012, 14, { x: 0.02, y: 0.106, z: 0.06, rz: -Z }, dark(0x22252a));
    // 镜座：底面压在导轨齿顶 0.066，顶端仍到 0.1 托住镜筒（镜筒/光轴高度不变）
    for (const z of [0.0, 0.1]) b.box(0.02, 0.034, 0.016, { y: 0.066, z }, dark(0x1a1c1f));
    b.cyl(0.021, 0.021, 0.001, 20, { y: 0.106, z: 0.149, rx: Z }, glow(0x3a7aff, 1.4));
    b.cyl(0.017, 0.017, 0.001, 20, { y: 0.106, z: -0.009, rx: Z }, glow(0x0a1420, 0.6));
    sightY = 0.106;
    sightZ = -0.01;
    relief = 0.1;
  } else if (t >= 4) {
    // 开放式反射瞄具：以前是实心镜身 + 不透明的镜片，红点还画在镜片上沿外面，开镜只看到一团黑。
    // 现在是一个空心方框（底座、两侧壁、顶盖），中间的窗口正对瞄准点，透过去就是战场；
    // 分划是发光的"圆圈 + 点"，点的中心就是弹着点
    const z0 = 0.002;
    const len = 0.046;
    const frame = poly(0x17181a);
    b.box(0.034, 0.008, len, { y: 0.064, z: z0 }, frame); // 底座（嵌在导轨齿间，导轨齿顶 0.066）
    for (const x of [0.0152, -0.0152]) b.box(0.0036, 0.034, len, { x, y: 0.072, z: z0 }, frame);
    b.rbox(0.034, 0.0036, len, 0.0012, { y: 0.106, z: z0 }, frame); // 顶盖
    b.box(0.006, 0.008, 0.012, { x: 0.02, y: 0.09, z: z0 }, dark(0x22252a)); // 亮度旋钮
    // 镜片只做一圈很淡的镀膜边，中间留空（发光材质不透明，铺满会挡住视线）
    const coat = glow(0x2a5a6a, 0.8);
    for (const x of [0.0131, -0.0131]) b.box(0.0008, 0.034, 0.001, { x, y: 0.072, z: z0 + len / 2 - 0.004 }, coat);
    const rz = z0 + len / 2 - 0.006; // 分划面
    b.cyl(0.0011, 0.0011, 0.001, 10, { y: AIM, z: rz, rx: Z }, glow(0xff3020, 4));
    b.torus(0.0062, 0.00035, 4, 32, { y: AIM, z: rz }, glow(0xff3a28, 2.2));
    sightY = AIM;
    sightZ = z0 - len / 2;
    relief = 0.17;
    // 机械准星折倒（贴在导轨上），不和红点抢视线
    b.box(0.012, 0.004, 0.018, { y: 0.064, z: frontZ }, sightCol);
  } else {
    // 觇孔照门：以前孔只有 4 mm、离眼睛 0.2 m，准星又细到屏幕上只剩两三个像素，开镜几乎看不到瞄准点。
    // 现在眼睛贴近照门（"鬼环"觇孔），孔在屏幕上是一个大圆环，准星柱和发光准星点套在圆环正中
    const rz = -0.01;
    b.box(0.026, 0.008, 0.026, { y: 0.064, z: rz }, dark(0x1a1c1f)); // 底座
    b.box(0.006, 0.011, 0.006, { y: 0.072, z: rz }, sightCol); // 觇孔立柱
    b.torus(0.0046, 0.0012, 6, 20, { y: AIM, z: rz }, sightCol);
    // 两侧护耳：顶端 0.092，和觇孔环顶（约 0.094）差不多高，从两侧护着觇孔
    for (const x of [0.0095, -0.0095]) b.box(0.003, 0.02, 0.008, { x, y: 0.072, z: rz }, dark(0x1a1c1f));
    sightY = AIM;
    sightZ = rz;
    relief = 0.12;
    // 准星：细柱子顶端是发光准星点（橙色，2 级起换绿色氚光），点的中心就是弹着点
    const postW = 0.006;
    const dotTop = AIM + postW / 2;
    b.box(0.014, 0.006, 0.016, { y: 0.064, z: frontZ }, sightCol); // 准星座（导轨上）
    b.box(postW, dotTop - 0.07, 0.005, { y: 0.07, z: frontZ }, sightCol);
    // 橙色点（0~1 级）做大一点、更亮（7.5mm），免得被发电机的辉光吞掉；中心仍在 AIM
    const dotS = t >= 2 ? postW : 0.0075;
    b.box(dotS, dotS, 0.001, { y: AIM - dotS / 2, z: frontZ - 0.003 }, t >= 2 ? glow(0x9dffa8, 3.2) : glow(0xffa040, 3.6));
    // 1 级起：准星护翼（准星两侧的竖片）；内沿离中心 7.7mm，和 7.5mm 的点之间留出约 4mm 亮缝
    if (t >= 1) for (const x of [0.009, -0.009]) b.box(0.0026, 0.024, 0.008, { x, y: 0.07, z: frontZ }, sightCol);
  }
  // 5 级：发光的前握把
  if (t >= 5) {
    b.rbox(0.028, 0.07, 0.03, 0.008, { y: -0.08, z: 0.3 }, poly(0x1a1c1e));
    b.box(0.002, 0.05, 0.004, { x: 0.0145, y: -0.072, z: 0.3 }, glow(0x4aa8ff, 2.2));
  }
  // 8 级：激光指示器
  if (t >= 8) {
    b.rbox(0.022, 0.022, 0.06, 0.004, { x: 0.034, y: 0.02, z: 0.38 }, poly(0x17181a));
    b.cyl(0.004, 0.004, 0.001, 10, { x: 0.034, y: 0.031, z: 0.411, rx: Z }, glow(0xff2a1a, 3));
  }

  return {
    gripR: new Vector3(0, -0.075, -0.02),
    gripL: new Vector3(0, -0.012, t >= 5 ? 0.3 : 0.32),
    muzzle: new Vector3(0, 0.028, muzzleZ),
    eject: new Vector3(-0.024, 0.02, 0.12),
    sight: new Vector3(0, sightY, sightZ),
    eyeRelief: relief,
    slideTravel: 0.04,
    action: 'auto',
  };
}
